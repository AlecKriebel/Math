#!/usr/bin/env python3
"""Exact, dependency-free controls for the PR1129 geometric interfaces.

This does not compute any unknown odd SOS certificate or prove Scheiderer's theorem.
All inputs below are independently encoded from the audited mathematical statements.
The universal arguments are in REPORT.md; these finite checks guard their interfaces.
"""
from fractions import Fraction as F
from itertools import combinations, product
from math import comb
import json
import sys

checks = 0
controls = []

def require(value, label):
    global checks
    checks += 1
    if not value:
        raise RuntimeError(label)

def rank(matrix, ncols):
    a = [[F(x) for x in row] for row in matrix]
    rr = 0
    for cc in range(ncols):
        pivot = next((i for i in range(rr, len(a)) if a[i][cc]), None)
        if pivot is None:
            continue
        a[rr], a[pivot] = a[pivot], a[rr]
        q = a[rr][cc]
        a[rr] = [x/q for x in a[rr]]
        for i in range(len(a)):
            if i != rr and a[i][cc]:
                q = a[i][cc]
                a[i] = [x-q*y for x,y in zip(a[i], a[rr])]
        rr += 1
    return rr

cech_rows = []
for mask in range(16):
    neg = {i for i in range(4) if mask & (1 << i)}
    terms = [[s for s in combinations(range(4), p+1) if neg <= set(s)] for p in range(4)]
    diffs = []
    ranks = []
    for p in range(3):
        rows = []
        for out in terms[p+1]:
            row = []
            for inp in terms[p]:
                row.append(sum((-1)**j for j in range(len(out)) if out[:j]+out[j+1:] == inp))
            rows.append(row)
        diffs.append(rows)
        ranks.append(rank(rows, len(terms[p])))
    for p in range(2):
        for i in range(len(terms[p+2])):
            for j in range(len(terms[p])):
                require(sum(diffs[p+1][i][k]*diffs[p][k][j] for k in range(len(terms[p+1]))) == 0,
                        'Cech differential squared')
    cohom = [len(terms[p]) - (ranks[p-1] if p else 0) - (ranks[p] if p < 3 else 0) for p in range(4)]
    expected = [int(mask == 0), 0, 0, int(mask == 15)]
    require(cohom == expected, 'Cech negative-support cohomology')
    cech_rows.append({'negative_support': sorted(neg), 'term_dimensions': list(map(len, terms)), 'differential_ranks': ranks, 'cohomology_dimensions': cohom})

# Source monomial (a,b,c,d) maps to target exponent (2a+b+d,a+2b+d,3c+d).
def monomials(t):
    for a in range(t+1):
        for b in range(t-a+1):
            for c in range(t-a-b+1):
                yield a,b,c,t-a-b-c

def image_exp(v):
    a,b,c,d = v
    return 2*a+b+d, a+2*b+d, 3*c+d

def normal(v):
    a,b,c,d = v
    n,r = divmod(d,3)
    return a+n,b+n,c+n,r

monomial_count = 0
for t in range(37):
    by_target = {}
    normal_to_target = {}
    for v in monomials(t):
        monomial_count += 1
        w = image_exp(v)
        n = normal(v)
        require(sum(w) == 3*t, 'homogeneous degree under substitution')
        require(image_exp(n) == w, 'D^3=ABC normal reduction')
        if w in by_target:
            require(by_target[w] == n, 'all collisions generated by cubic relation')
        by_target[w] = n
        if n in normal_to_target:
            require(normal_to_target[n] == w, 'well-defined normal form image')
        normal_to_target[n] = w
    hilbert = comb(t+3,3) - (comb(t,3) if t >= 3 else 0)
    require(len(by_target) == hilbert, 'hypersurface Hilbert function')
    require(len(normal_to_target) == hilbert, 'normal form basis size')

# Positivity controls on rational real torus points with both projective signs.
values = sorted(set(F(s*n,d) for s in (-1,1) for n in (1,2,3) for d in (1,2,3,5)))
params = [F(-11), F(-1), F(0), F(1), F(2), F(2999999,1000000)]
positivity_count = 0
for a,b,cparam,scale in product(values,values,params,(-3,-1,1,2)):
    A,B,C,D = scale*a, scale*b, scale/(a*b), F(scale)
    require(A*B*C == D**3, 'signed torus relation')
    q = A*A+B*B+C*C-cparam*D*D
    require(q >= (3-cparam)*D*D > 0, 'rational signed torus positivity')
    positivity_count += 1

boundary_count = 0
for A,B,C in product(range(-3,4), repeat=3):
    if (A,B,C) != (0,0,0) and A*B*C == 0:
        for cparam in params:
            require(A*A+B*B+C*C > 0, 'D=0 boundary positivity')
            boundary_count += 1

# Compute exact symbolic input identities by exponent dictionaries.
q = {(2,0,0,0):F(1),(0,2,0,0):F(1),(0,0,2,0):F(1),(0,0,0,2):F(-2)}
q_image = {image_exp(v):coef for v,coef in q.items()}
require(q_image == {(4,2,0):1,(2,4,0):1,(0,0,6):1,(2,2,2):-2}, 'exact parameter family at c=2')
require(image_exp((1,1,1,0)) == image_exp((0,0,0,3)), 'cubic relation killed')
for N in range(100):
    m=N+1
    require((m % 2 == 1) == (N % 2 == 0), 'exponent parity')
    require(2*m*3 == 6*m and (3*m)*2 == 6*m, 'section degree balance')

# Falsification controls must actually refute the listed invalid shortcuts.
def control(label, refutation):
    require(refutation, 'control did not refute: '+label)
    controls.append(label)

control('strict positivity cannot be extended to c=3', 1+1+1-3 == 0)
control('above-endpoint odd powers cannot be SOS', (3-F(3001,1000))**3 < 0)
control('an even power being SOS does not certify nonnegativity of the base', (-1)**2 > 0 and -1 < 0)
control('odd N has wrong output parity', ((5+1) % 2) == 0)
control('M_c is not positive definite on the projective plane', (1**4*0**2+1**2*0**4+0**6-2*1**2*0**2*0**2) == 0)
for point in ((1,0,0),(0,1,0)):
    x,y,z = point
    control('substitution has base point '+str(point), (x*x*y,x*y*y,z*z*z,x*y*z) == (0,0,0,0))
control('wrong cubic coefficient is not killed', 1*1*1-2*(1**3) != 0)
control('omitting the parameter square changes the exact target', 1+1+1 != 1+1+1-2)
# Under image D=xy*z^2, source G has unequal target monomial exponents.
control('changing the D substitution breaks the relation and degrees', (3,3,3) != (3,3,6))

summary = {
 'status':'PASS', 'python':sys.version.split()[0], 'explicit_requirements_checked':checks,
 'cech_negative_support_types':len(cech_rows), 'cech_data':cech_rows,
 'monomial_degrees':[0,36], 'source_monomials_checked':monomial_count,
 'rational_torus_samples':positivity_count, 'boundary_samples':boundary_count,
 'adverse_controls':controls,
 'scope':'Exact interface and falsification checks, not an SOS certificate or proof of the imported theorem.'
}
print(json.dumps(summary, indent=2))
