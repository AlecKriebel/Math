#!/usr/bin/env python3
"""Independent finite checks and isolated all-mode sealed-checker replay.

All generated replay/mutant scripts remain in --scratch; input files are read only.
The quantified arguments are in REPORT.md, not inferred from these finite loops.
"""
import argparse
import datetime
from fractions import Fraction
import hashlib
import itertools
import json
from pathlib import Path
import subprocess
import sys


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def product(x, y):
    # Derive coefficients directly from (sqrt(10))^2 = 10.
    return (x[0]*y[0] + 10*x[1]*y[1], x[0]*y[1] + x[1]*y[0])


def field_norm(x):
    return product(x, (x[0], -x[1]))[0]


def independent_worker():
    residues = {a*a % 5 for a in range(5)}
    require(residues == {0, 1, 4}, 'square residues incorrect')
    require(all(t % 5 not in residues for t in [-3, -2, 2, 3]),
            'forbidden signed norm obstruction lost')
    good_pairs = [(t,u) for t,u in itertools.product(range(4), repeat=2)
                  if (t*t-10*u*u) % 4 == 0]
    require(good_pairs == [(0,0),(0,2),(2,0),(2,2)],
            'integral trace parity obstruction lost')
    denominators = [s for s in range(1, 7) if 40 % (s*s) == 0]
    require(denominators == [1,2], 'denominator divisibility incorrect')
    # A neighboring field is a deliberate control: its half-integer IS integral.
    require((1*1-5*1*1) % 4 == 0, 'Q(sqrt(5)) boundary control failed')
    require(Fraction(1,4)-10*Fraction(1,4) == Fraction(-9,4),
            'half-integer Q(sqrt(10)) control failed')
    elems = list(itertools.product(range(-4,5), repeat=2))
    for x,y in itertools.product(elems, repeat=2):
        require(field_norm(product(x,y)) == field_norm(x)*field_norm(y),
                'finite norm multiplicativity check failed')
    mod2 = list(itertools.product(range(2), repeat=2))
    require(len(mod2)==4 and {x[0] % 2 for x in mod2}=={0,1},
            'principal/nonprincipal quotient cardinalities incorrect')
    require([x for x in mod2 if x[0] % 2 == 0]==[(0,0),(0,1)],
            'prime ideal kernel classes incorrect')
    for x,y in itertools.product(mod2, repeat=2):
        require(product(x,y)[0] % 2 == (x[0]*y[0]) % 2,
                'constant-coefficient quotient is not multiplicative')
        require((x[0]+y[0]) % 2 == (x[0]%2+y[0]%2) % 2,
                'constant-coefficient quotient is not additive')
    require(product((0,1),(0,1)) == (10,0), 'nonprime witness failed')
    require(10 % 2 == 0 and 1 % 2 != 0, 'nonprime coefficient witness failed')
    require(field_norm((2,0)) == 4, 'principal ideal norm witness failed')
    # P^2 is generated by 4, 2 sqrt(10), 10. 2 = 10 - 2*4.
    require(10 - 2*4 == 2, 'ramified ideal identity failed')
    # Zero-divisors in R/(2) distinguish the quotient from R/P = F_2.
    require((product((0,1),(0,1))[0] % 2,
             product((0,1),(0,1))[1] % 2) == (0,0),
            'nonzero nilpotent in R/(2) lost')
    return {
        'scope': 'finite identities, complete residues, and boundary controls only',
        'square_residues_mod5': sorted(residues),
        'forbidden_signed_norms': [-3,-2,2,3],
        'trace_coefficient_pairs_mod4': good_pairs,
        'denominators_with_square_dividing40': denominators,
        'finite_norm_pairs_checked': len(elems)**2,
        'complete_mod2_quotient_pairs_checked': len(mod2)**2,
        'prime_ideal_quotient_size': 2,
        'principal_ideal_2_quotient_size': 4,
        'neighbor_Qsqrt5_half_integer_integral_control': True,
        'all_checks_passed': True,
    }


def orchestrate(source, scratch):
    source = source.resolve()
    scratch.mkdir(parents=True, exist_ok=True)
    manifest = json.loads((source/'MANIFEST.json').read_text())
    require(manifest['schema'] == 'authored-file-manifest-v1', 'unknown source schema')
    authenticated=[]
    for row in manifest['files']:
        b=(source/row['relative_path']).read_bytes()
        require(len(b)==row['size_bytes'], 'source byte count mismatch')
        require(hashlib.sha256(b).hexdigest()==row['sha256'], 'source SHA mismatch')
        authenticated.append(row['relative_path'])
    original=(source/'finite_checks.py').read_text()
    copied=scratch/'sealed_finite_checks_copy.py'
    copied.write_text(original)
    expected=json.loads((source/'FINITE_CHECK_RESULTS.json').read_text())
    modes=[('normal',[]),('-O',['-O']),('-OO',['-OO'])]
    baseline=[]
    independent=[]
    for name,flags in modes:
        r=subprocess.run([sys.executable,*flags,str(copied)],cwd=scratch,
                         capture_output=True,text=True)
        require(r.returncode==0, f'sealed checker failed under {name}: {r.stderr}')
        require(json.loads(r.stdout)==expected, 'sealed semantic result mismatch')
        require(r.stdout==(source/'FINITE_CHECK_RESULTS.json').read_text(),
                'sealed byte result mismatch')
        baseline.append({'mode':name,'returncode':r.returncode,
                         'stdout_sha256':hashlib.sha256(r.stdout.encode()).hexdigest(),
                         'matches_sealed_bytes':True})
        r=subprocess.run([sys.executable,*flags,str(Path(__file__).resolve()),'--worker'],
                         cwd=scratch,capture_output=True,text=True)
        require(r.returncode==0, f'independent worker failed under {name}: {r.stderr}')
        independent.append({'mode':name,'result':json.loads(r.stdout)})
    require(all(x['result']==independent[0]['result'] for x in independent),
            'independent modes disagree')
    # Mutants test distinct existing guards in the SEALED checker, not our claims.
    changes=[
        ('wrong_mod5_table','squares5 == [0, 1, 4]','squares5 == [0, 1, 2]',
         'Incorrect square residues modulo 5'),
        ('wrong_quotient_coordinate','return x[0] % 2','return x[1] % 2',
         'Quotient map failed multiplicativity'),
        ('wrong_ring_relation','a * c + 10 * b * d','a * c + 11 * b * d',
         'Quotient map failed multiplicativity'),
        ('wrong_two_divisibility','coefficient % 2 == 0','coefficient % 3 == 0',
         '2 must divide sqrt(10)^2'),
        ('wrong_integral_denominator','40 % (s * s) == 0','36 % (s * s) == 0',
         'Quadratic integral-element denominator reduction failed'),
        ('wrong_trace_congruence','(t * t - 10 * u * u) % 4 == 0',
         '(t * t - 9 * u * u) % 4 == 0',
         'Integral-element parity reduction failed'),
    ]
    negative=[]
    for label,old,new,error in changes:
        require(original.count(old)==1, f'mutant ambiguous: {label}')
        target=scratch/(label+'.py')
        target.write_text(original.replace(old,new,1))
        for name,flags in modes:
            r=subprocess.run([sys.executable,*flags,str(target)],cwd=scratch,
                             capture_output=True,text=True)
            require(r.returncode!=0 and error in r.stderr,
                    f'negative control not rejected at expected guard: {label} {name}')
            negative.append({'mutation':label,'mode':name,'returncode':r.returncode,
                             'expected_exception_message':error,'rejected':True})
    return {
        'created_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),
        'python_version':sys.version,
        'input_manifest_schema':manifest['schema'],
        'authenticated_source_files':authenticated,
        'sealed_checker_replays':baseline,
        'independent_worker_replays':independent,
        'negative_controls':negative,
        'all_checks_passed':True,
        'no_universal_proof_from_finite_enumeration':True,
    }


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--worker',action='store_true')
    parser.add_argument('--source',type=Path)
    parser.add_argument('--scratch',type=Path)
    parser.add_argument('--output',type=Path)
    args=parser.parse_args()
    if args.worker:
        print(json.dumps(independent_worker(),indent=2,sort_keys=True))
    else:
        require(args.source is not None and args.scratch is not None,
                '--source and --scratch required')
        result=orchestrate(args.source,args.scratch)
        text=json.dumps(result,indent=2,sort_keys=True)+'\n'
        if args.output:
            args.output.write_text(text)
        else:
            print(text,end='')


if __name__=='__main__':
    main()
