#!/usr/bin/env python3
"""Semantic contract and mutation tests for a replacement atlas certificate.

JSON Schema alone cannot detect a separator attached to the wrong pair.  This
contract therefore requires content-addressed IDs and checks all references,
the raw-to-canonical transport, exact pair coverage, and witness direction.
The embedded fixture is deliberately tiny; the same checks are intended for
the full atlas compiler and an independently generated reviewer artifact.
"""

from __future__ import annotations

from copy import deepcopy
from hashlib import sha256
import json


def digest(value: object) -> str:
    return sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def graph_id(payload: dict) -> str:
    return digest({"kind": "graph-v1", "payload": payload})


def pair_id(source: str, target: str, direction: str, port_map: dict) -> str:
    return digest({"kind": "pair-v1", "source": source, "target": target, "direction": direction, "port_map": port_map})


def validate(certificate: dict, reviewer_manifest: dict) -> None:
    if certificate.get("schema") != "stc-jc-decorated-atlas-v1":
        raise AssertionError("schema")
    graphs = certificate["canonical_graphs"]
    if set(graphs) != {graph_id(value["payload"]) for value in graphs.values()}:
        raise AssertionError("canonical graph content address")
    raw = certificate["raw_presentations"]
    for row in raw:
        target = row["canonical_graph_id"]
        if target not in graphs:
            raise AssertionError("raw canonical reference")
        transport = row["raw_to_canonical"]
        if sorted(transport["vertex_map"].values()) != sorted(graphs[target]["payload"]["vertices"]):
            raise AssertionError("vertex bijection")
        if set(transport["port_map"]) != set(row["ports"]):
            raise AssertionError("port transport")

    expected = {tuple(x) for x in certificate["completeness"]["expected_pairs"]}
    observed = set()
    for row in certificate["pairs"]:
        key = (row["source_graph_id"], row["target_graph_id"], row["direction"])
        if key in observed:
            raise AssertionError("duplicate pair")
        observed.add(key)
        expected_id = pair_id(row["source_graph_id"], row["target_graph_id"], row["direction"], row["port_map"])
        if row["pair_id"] != expected_id:
            raise AssertionError("pair content address")
        witness = row["witness"]
        if witness["source_pullback"]["zero"] is not True:
            raise AssertionError("wrong identity side")
        if witness["target_pullback"]["zero"] is not False or witness["target_sign"] not in (-1, 1):
            raise AssertionError("target is not strictly separated")
        if witness["polynomial_hash"] != digest(witness["target_pullback"]["terms"]):
            raise AssertionError("polynomial hash")
        if witness["binding_hash"] != digest({
            "pair_id": row["pair_id"],
            "marginal": witness["marginal"],
            "invariant": witness["invariant"],
            "source_pullback": witness["source_pullback"],
            "target_pullback": witness["target_pullback"],
            "target_sign": witness["target_sign"],
        }):
            raise AssertionError("pair/polynomial binding")
    if observed != expected:
        raise AssertionError("incomplete pair universe")
    if certificate["completeness"]["pair_count"] != len(observed):
        raise AssertionError("pair count")
    if certificate["completeness"]["pair_set_hash"] != digest(sorted(observed)):
        raise AssertionError("pair set hash")
    # This manifest must be regenerated by the independent implementation from
    # primitive inputs; it is not copied from the submitted certificate.
    if observed != {tuple(x) for x in reviewer_manifest["expected_pairs"]}:
        raise AssertionError("independent expected-pair universe")
    if set(graphs) != set(reviewer_manifest["canonical_graph_ids"]):
        raise AssertionError("independent canonical-graph universe")
    if digest(sorted(observed)) != reviewer_manifest["pair_set_hash"]:
        raise AssertionError("independent pair-set hash")


def fixture() -> dict:
    source_payload = {"vertices": ["a", "b"], "edges": [["a", "b"]], "ports": {"p": "a"}}
    target_payload = {"vertices": ["u", "v"], "edges": [["u", "v"]], "ports": {"p": "u"}}
    source = graph_id(source_payload); target = graph_id(target_payload)
    port_map = {"p": "p"}; direction = "source_preceq_target"
    pid = pair_id(source, target, direction, port_map)
    source_pullback = {"zero": True, "terms": []}
    target_pullback = {"zero": False, "terms": [[[1], 1], [[0], -1]]}
    marginal = ["p", "q", "r"]; invariant = "F"
    witness = {
        "marginal": marginal,
        "invariant": invariant,
        "source_pullback": source_pullback,
        "target_pullback": target_pullback,
        "target_sign": -1,
        "polynomial_hash": digest(target_pullback["terms"]),
    }
    witness["binding_hash"] = digest({
        "pair_id": pid, "marginal": marginal, "invariant": invariant,
        "source_pullback": source_pullback, "target_pullback": target_pullback,
        "target_sign": -1,
    })
    expected = [(source, target, direction)]
    return {
        "schema": "stc-jc-decorated-atlas-v1",
        "generator": {"source_sha256": "0" * 64, "input_manifest_sha256": "1" * 64},
        "canonical_graphs": {
            source: {"payload": source_payload},
            target: {"payload": target_payload},
        },
        "raw_presentations": [
            {"raw_id": "r0", "canonical_graph_id": source, "ports": {"p": "a"},
             "raw_to_canonical": {"vertex_map": {"A": "a", "B": "b"}, "edge_map": {"A>B": "a>b"}, "port_map": {"p": "p"}}},
            {"raw_id": "r1", "canonical_graph_id": target, "ports": {"p": "u"},
             "raw_to_canonical": {"vertex_map": {"U": "u", "V": "v"}, "edge_map": {"U>V": "u>v"}, "port_map": {"p": "p"}}},
        ],
        "pairs": [{"pair_id": pid, "source_graph_id": source, "target_graph_id": target,
                   "direction": direction, "port_map": port_map, "witness": witness}],
        "completeness": {"expected_pairs": expected, "pair_count": 1, "pair_set_hash": digest(sorted(expected))},
    }


def reviewer_manifest(certificate: dict) -> dict:
    """Tiny stand-in for output regenerated by a second implementation."""
    expected = [tuple(row) for row in certificate["completeness"]["expected_pairs"]]
    return {
        "primitive_input_sha256": "2" * 64,
        "reviewer_source_sha256": "3" * 64,
        "canonical_graph_ids": sorted(certificate["canonical_graphs"]),
        "expected_pairs": expected,
        "pair_set_hash": digest(sorted(expected)),
    }


def mutation_test() -> dict:
    base = fixture(); manifest = reviewer_manifest(base); validate(base, manifest)
    mutations = {}

    def rejected(name, edit):
        candidate = deepcopy(base); edit(candidate)
        try:
            validate(candidate, manifest)
        except (AssertionError, KeyError, TypeError):
            mutations[name] = "REJECTED"
            return
        raise AssertionError(f"mutation escaped: {name}")

    rejected("omitted_pair", lambda c: c["pairs"].clear())
    rejected("duplicated_pair", lambda c: c["pairs"].append(deepcopy(c["pairs"][0])))
    rejected("reversed_direction", lambda c: c["pairs"][0].__setitem__("direction", "target_preceq_source"))
    rejected("swapped_polynomial", lambda c: c["pairs"][0]["witness"]["target_pullback"].__setitem__("terms", [[[2], 1]]))
    rejected("wrong_zero_side", lambda c: c["pairs"][0]["witness"]["source_pullback"].__setitem__("zero", False))
    rejected("missing_transport", lambda c: c["raw_presentations"][0]["raw_to_canonical"].pop("vertex_map"))
    rejected("mutated_graph", lambda c: c["canonical_graphs"][next(iter(c["canonical_graphs"]))]["payload"]["vertices"].append("x"))
    rejected("stale_pair_set_hash", lambda c: c["completeness"].__setitem__("pair_set_hash", "f" * 64))

    def coordinated_internal_rewrite(c):
        row = c["pairs"][0]
        row["direction"] = "target_preceq_source"
        row["pair_id"] = pair_id(row["source_graph_id"], row["target_graph_id"], row["direction"], row["port_map"])
        witness = row["witness"]
        witness["binding_hash"] = digest({
            "pair_id": row["pair_id"], "marginal": witness["marginal"], "invariant": witness["invariant"],
            "source_pullback": witness["source_pullback"], "target_pullback": witness["target_pullback"],
            "target_sign": witness["target_sign"],
        })
        expected = [(row["source_graph_id"], row["target_graph_id"], row["direction"])]
        c["completeness"]["expected_pairs"] = expected
        c["completeness"]["pair_set_hash"] = digest(sorted(expected))

    rejected("coordinated_internal_rewrite", coordinated_internal_rewrite)
    return {"baseline": "ACCEPTED", "mutations": mutations, "all_mutations_rejected": len(mutations) == 9}


if __name__ == "__main__":
    print(json.dumps(mutation_test(), indent=2, sort_keys=True))
