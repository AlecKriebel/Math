def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def qstring(value: Q) -> str:
    if value.denominator == 1:
        return str(value.numerator)
    return f"{value.numerator}/{value.denominator}"


def popcount(value: int) -> int:
    """Python-3.8-compatible population count."""

    return bin(value).count("1")


def edge_color(
    edges: tuple[int, ...], first: int, second: int
) -> int:
    return edges[PAIR_INDEX7[tuple(sorted((first, second)))]]


def local_memberships(
    edges: tuple[int, ...],
    vertices: tuple[int, ...],
    first: int,
    second: int,
    threshold_index: int,
    table: tuple[int, ...],
) -> tuple[int, int, int, int]:
    """Return h,g,i,c for one oriented base inside ``vertices``."""

    remaining = tuple(
        vertex for vertex in vertices if vertex not in (first, second)
    )
    depth = 0
    common = 0
    intersection = 0
    for vertex in remaining:
        first_index = edge_color(edges, first, vertex)
        second_index = edge_color(edges, second, vertex)
        in_depth = bool(table[7 * first_index + second_index])
        in_common = (
            first_index >= threshold_index
            and second_index >= threshold_index
        )
        depth += int(in_depth)
        common += int(in_common)
        intersection += int(in_depth and in_common)
    distinct = depth * common - intersection
    return depth, common, intersection, distinct


def primitive_k7_slack(
    edges: tuple[int, ...],
    base_index: int,
    threshold_index: int,
    capacity: int,
    required: int,
    table: tuple[int, ...],
) -> int:
    """Sum the primitive K7 row over oriented base-colored edges.

    For one oriented base the exact cleared row is

      78 M h + 78 r g - 10 r M - 741 c - 78 i >= 0.

    The returned value sums both orientations of every matching unordered
    base edge.  It is the same convention called the twice-symmetrized
    atom slack by the adjacent K5 and K6 verifiers.
    """

    vertices = tuple(range(7))
    answer = 0
    for position, (first, second) in enumerate(PAIRS7):
        if edges[position] != base_index:
            continue
        for oriented_first, oriented_second in (
            (first, second),
            (second, first),
        ):
            h, g, intersection, distinct = local_memberships(
                edges,
                vertices,
                oriented_first,
                oriented_second,
                threshold_index,
                table,
            )
            answer += (
                78 * capacity * h
                + 78 * required * g
                - 10 * required * capacity
                - 741 * distinct
                - 78 * intersection
            )
    return answer


def deleted_k6_slack(
    edges: tuple[int, ...],
    deleted: int,
    base_index: int,
    threshold_index: int,
    capacity: int,
    required: int,
    table: tuple[int, ...],
) -> int:
    """K6 product form on the face obtained by deleting one K7 vertex."""

    vertices = tuple(vertex for vertex in range(7) if vertex != deleted)
    answer = 0
    for first, second in itertools.combinations(vertices, 2):
        if edge_color(edges, first, second) != base_index:
            continue
        for oriented_first, oriented_second in (
            (first, second),
            (second, first),
        ):
            h, g, intersection, distinct = local_memberships(
                edges,
                vertices,
                oriented_first,
                oriented_second,
                threshold_index,
                table,
            )
            answer += (
                39 * capacity * h
                + 39 * required * g
                - 4 * required * capacity
                - 494 * distinct
                - 39 * intersection
            )
    return answer


def set_pattern_k7_slack(
    depth_mask: int,
    common_mask: int,
    capacity: int,
    required: int,
) -> int:
    """Primitive one-oriented-base row for abstract five-point sets."""

    depth = popcount(depth_mask)
    common = popcount(common_mask)
    intersection = popcount(depth_mask & common_mask)
    distinct = depth * common - intersection
    return (
        78 * capacity * depth
        + 78 * required * common
        - 10 * required * capacity
        - 741 * distinct
        - 78 * intersection
    )


def set_pattern_deleted_sum(
    depth_mask: int,
    common_mask: int,
    capacity: int,
    required: int,
) -> int:
    """Sum the five relevant K6 face rows for abstract membership sets."""

    answer = 0
    for deleted in range(5):
        retained_mask = ((1 << 5) - 1) ^ (1 << deleted)
        depth = popcount(depth_mask & retained_mask)
        common = popcount(common_mask & retained_mask)
        intersection = popcount(
            depth_mask & common_mask & retained_mask
        )
        distinct = depth * common - intersection
        answer += (
            39 * capacity * depth
            + 39 * required * common
            - 4 * required * capacity
            - 494 * distinct
            - 39 * intersection
        )
    return answer


def verify_sampling_and_abstract_identity() -> dict[str, object]:
    """Verify finite-population factors and the deletion identity."""

    total_samples = comb(
        GLOBAL_RESIDUAL_VERTICES, K7_RESIDUAL_VERTICES
    )
    one_point_samples = comb(
        GLOBAL_RESIDUAL_VERTICES - 1,
        K7_RESIDUAL_VERTICES - 1,
    )
    ordered_pair_samples = comb(
        GLOBAL_RESIDUAL_VERTICES - 2,
        K7_RESIDUAL_VERTICES - 2,
    )
    one_point_probability = Q(one_point_samples, total_samples)
    ordered_pair_probability = Q(
        ordered_pair_samples, total_samples
    )
    assert one_point_probability == Q(5, 39)
    assert ordered_pair_probability == Q(10, 741)

    # The cleared K7 row is exactly ten times the global product row after
    # taking expectations: 78*(5/39)=10 and 741*(10/741)=10.
    assert 78 * one_point_probability == 10
    assert 741 * ordered_pair_probability == 10

    patterns_checked = 0
    for _base, _threshold, capacity in FAMILIES:
        for required in range(8):
            for depth_mask in range(1 << 5):
                for common_mask in range(1 << 5):
                    primitive = set_pattern_k7_slack(
                        depth_mask,
                        common_mask,
                        capacity,
                        required,
                    )
                    deleted = set_pattern_deleted_sum(
                        depth_mask,
                        common_mask,
                        capacity,
                        required,
                    )
                    assert deleted == 2 * primitive
                    patterns_checked += 1
    assert patterns_checked == 7 * 8 * 32 * 32

    return {
        "one_point_inclusion_probability": qstring(
            one_point_probability
        ),
        "ordered_distinct_pair_inclusion_probability": qstring(
            ordered_pair_probability
        ),
        "cleared_k7_row": (
            "741*c + 78*i <= "
            "78*M*h + 78*r*g - 10*r*M*E"
        ),
        "abstract_membership_identities": patterns_checked,
        "deleted_k6_sum_multiplier": 2,
        "uniform_deleted_face_expectation_factor": "2/7",
    }


def parsed_mixture(
    path: Path,
    expected_sha256: str,
    expected_schema: str,
    expected_atoms: int,
) -> tuple[dict[str, object], tuple[tuple[int, ...], ...], tuple[Q, ...]]:
    assert digest(path) == expected_sha256
    certificate = json.loads(path.read_text())
    assert certificate["schema"] == expected_schema
    atoms = certificate["atoms"]
    assert len(atoms) == certificate["positive_atom_count"] == expected_atoms
    edges = tuple(tuple(atom[EDGE_KEY]) for atom in atoms)
    assert all(
        len(item) == 21 and all(0 <= color < 7 for color in item)
        for item in edges
    )
    weights = tuple(Q(atom["weight"]) for atom in atoms)
    assert all(weight > 0 for weight in weights)
    assert sum(weights) == 1
    return certificate, edges, weights


def state_catalog(
    grid: tuple[Q, ...],
    triples: tuple[tuple[int, int, int], ...],
) -> tuple[
    tuple[
        int,
        int,
        int,
        tuple[tuple[int, tuple[int, ...]], ...],
    ],
    ...,
]:
    encoded_families = direction_source.capacity_families(grid)
    expected_indices = tuple(
        (grid.index(base), grid.index(threshold), capacity)
        for base, threshold, capacity in FAMILIES
    )
    assert encoded_families == expected_indices
    result = []
    for base_index, threshold_index, capacity in encoded_families:
        states, coverage, _feasible = direction_source.direction_states(
            base_index, grid, triples
        )
        assert len(states) == coverage["distinct_states"]
        result.append(
            (
                base_index,
                threshold_index,
                capacity,
                states,
            )
        )
    assert tuple(len(item[3]) for item in result) == (
        62,
        62,
        80,
        88,
        92,
        92,
        84,
    )
    assert sum(len(item[3]) for item in result) == 560
    return tuple(result)


def audit_direct_k7(
    edges: tuple[tuple[int, ...], ...],
    weights: tuple[Q, ...],
    catalog: tuple[
        tuple[
            int,
            int,
            int,
            tuple[tuple[int, tuple[int, ...]], ...],
        ],
        ...,
    ],
    grid: tuple[Q, ...],
) -> dict[str, object]:
    """Audit the frozen 51-atom K7 mixture against all product states."""

    family_reports = []
    worst = None
    total_negative = 0
    for family_index, (
        base_index,
        threshold_index,
        capacity,
        states,
    ) in enumerate(catalog):
        values = []
        for state_index, (required, table) in enumerate(states):
            slack = sum(
                weight
                * primitive_k7_slack(
                    atom,
                    base_index,
                    threshold_index,
                    capacity,
                    required,
                    table,
                )
                for atom, weight in zip(edges, weights)
            )
            record = (
                slack,
                family_index,
                state_index,
                required,
                table,
            )
            values.append(record)
            if worst is None or record[0] < worst[0]:
                worst = record
        negative = sum(value[0] < 0 for value in values)
        total_negative += negative
        minimum = min(value[0] for value in values)
        family_reports.append(
            {
                "base_inner_product": qstring(grid[base_index]),
                "high_threshold": qstring(grid[threshold_index]),
                "capacity": capacity,
                "direction_states": len(states),
                "negative_rows": negative,
                "zero_rows": sum(value[0] == 0 for value in values),
                "minimum_primitive_k7_slack": qstring(minimum),
            }
        )

    assert worst is not None
    assert tuple(
        report["negative_rows"] for report in family_reports
    ) == EXPECTED_DIRECT_NEGATIVE_COUNTS
    assert total_negative == 45
    assert worst[0] == EXPECTED_DIRECT_WORST
    assert worst[1:4] == EXPECTED_DIRECT_WORST_STATE
    assert "".join(map(str, worst[4])) == EXPECTED_WORST_TABLE

    # Give an exact rational direction realizing the worst open-cell state,
    # rather than identifying the state only by a 49-bit membership table.
    base = grid[catalog[worst[1]][0]]
    orientation = 1
    endpoint_count = sum(
        direction_source.direction_audit.rational_qualifies(
            first,
            second,
            base,
            EXPECTED_WORST_RATIONAL_SLOPE,
            orientation,
        )
        for first, second in ((Q(1), base), (base, Q(1)))
    )
    rational_table = tuple(
        int(
            direction_source.direction_audit.rational_qualifies(
                first,
                second,
                base,
                EXPECTED_WORST_RATIONAL_SLOPE,
                orientation,
            )
        )
        for first in grid
        for second in grid
    )
    assert (7 - endpoint_count, rational_table) == (
        worst[3],
        worst[4],
    )

    return {
        "certificate_sha256": DIRECT_K7_SHA256,
        "positive_atoms": len(edges),
        "product_rows": 560,
        "negative_rows": total_negative,
        "negative_family": {
            "base_inner_product": "-1/4",
            "high_threshold": "1/2",
            "capacity": 3,
        },
        "strongest_negative_slack": qstring(worst[0]),
        "strongest_state": {
            "family_index": worst[1],
            "state_index": worst[2],
            "required_depth": worst[3],
            "rational_direction": (
                "(lambda,mu)=(1,"
                f"{qstring(EXPECTED_WORST_RATIONAL_SLOPE)})"
            ),
            "membership_table_row_major": EXPECTED_WORST_TABLE,
        },
        "families": family_reports,
    }


def verify_candidate_deletion_identities(
    certificate: dict[str, object],
    edges: tuple[tuple[int, ...], ...],
    weights: tuple[Q, ...],
    catalog: tuple[
        tuple[
            int,
            int,
            int,
            tuple[tuple[int, tuple[int, ...]], ...],
        ],
        ...,
    ],
) -> dict[str, object]:
    """Check 53*560 exact K7-to-K6 normalization identities."""

    identities = 0
    zero_keys = []
    minimum_positive = None
    for family_index, (
        base_index,
        threshold_index,
        capacity,
        states,
    ) in enumerate(catalog):
        for state_index, (required, table) in enumerate(states):
            weighted_slack = Q(0)
            for atom, weight in zip(edges, weights):
                primitive = primitive_k7_slack(
                    atom,
                    base_index,
                    threshold_index,
                    capacity,
                    required,
                    table,
                )
                deleted_sum = sum(
                    deleted_k6_slack(
                        atom,
                        deleted,
                        base_index,
                        threshold_index,
                        capacity,
                        required,
                        table,
                    )
                    for deleted in range(7)
                )
                assert deleted_sum == 2 * primitive
                identities += 1
                weighted_slack += weight * primitive
            assert weighted_slack >= 0
            if weighted_slack == 0:
                zero_keys.append([family_index, state_index, required])
            elif (
                minimum_positive is None
                or weighted_slack < minimum_positive
            ):
                minimum_positive = weighted_slack

    assert identities == 53 * 560
    assert zero_keys == certificate["zero_product_row_keys"]
    assert minimum_positive is not None
    assert qstring(minimum_positive) == certificate[
        "minimum_positive_twice_symmetrized_slack"
    ]
    return {
        "candidate_sha256": CANDIDATE_K7_SHA256,
        "positive_atoms": len(edges),
        "product_states": 560,
        "atom_state_deletion_identities": identities,
        "identity": "sum(seven deleted K6 forms) = 2*K7 form",
        "zero_product_rows": len(zero_keys),
        "minimum_positive_primitive_k7_slack": qstring(
            minimum_positive
        ),
        "induced_k6_expected_slack_factor": "2/7",
    }


def verify(
    source_path: Path = SOURCE,
    direct_k7_path: Path = DIRECT_K7,
    candidate_k7_path: Path = CANDIDATE_K7,
) -> dict[str, object]:
    assert digest(source_path) == SOURCE_SHA256
    assert digest(Path(direction_source.__file__).resolve()) == (
        DIRECTION_SOURCE_SHA256
    )
    assert digest(
        ROOT
        / "experiments"
        / "four_point_depth_projection"
        / "centered_quarter_pair_depth"
        / "verify.py"
    ) == DIRECTION_PARTITION_SHA256

    source = json.loads(source_path.read_text())
    assert source["schema"] == (
        "kissing5.centered_quarter_bv_pseudodistribution.v1"
    )
    grid = tuple(Q(value) for value in source["grid"])
    assert grid == (
        Q(-1),
        Q(-3, 4),
        Q(-1, 2),
        Q(-1, 4),
        Q(0),
        Q(1, 4),
        Q(1, 2),
    )
    triples = tuple(tuple(item) for item in source["triple_orbits"])
    catalog = state_catalog(grid, triples)

    sampling = verify_sampling_and_abstract_identity()
    _direct_certificate, direct_edges, direct_weights = parsed_mixture(
        direct_k7_path,
        DIRECT_K7_SHA256,
        "kissing5.centered_quarter_direct_k7_triangle_extension.v1",
        51,
    )
    direct_audit = audit_direct_k7(
        direct_edges, direct_weights, catalog, grid
    )
    candidate, candidate_edges, candidate_weights = parsed_mixture(
        candidate_k7_path,
        CANDIDATE_K7_SHA256,
        "kissing5.rank5_k7_product_extension.v1",
        53,
    )
    deletion_crosscheck = verify_candidate_deletion_identities(
        candidate,
        candidate_edges,
        candidate_weights,
        catalog,
    )

    return {
        "status": "PASS",
        "scope": (
            "seven currently proved quarter-grid capacity families; "
            "local K7 distributions only"
        ),
        "sampling_normalization": sampling,
        "stored_direct_k7_audit": direct_audit,
        "candidate_k7_deletion_crosscheck": deletion_crosscheck,
    }


if __name__ == "__main__":
    print(json.dumps(verify(), indent=2, sort_keys=True))
