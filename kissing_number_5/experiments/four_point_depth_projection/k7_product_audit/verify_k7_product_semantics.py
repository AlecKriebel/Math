#!/usr/bin/env python3
"""Exact K7 finite-population semantics and deletion cross-check.

This verifier has three purposes.

1. It derives the cleared K7 product row from sampling five of the 39
   vertices outside a fixed base edge.
2. It audits the frozen 51-atom direct K7 triangle extension against all
   560 currently encoded direction/capacity states.
3. For every one of the 53 atoms in the product-valid K7 candidate and
   every one of those 560 states, it checks the independent normalization
   identity

       sum over the seven deleted K6 faces of the K6 form
           = 2 times the primitive K7 form.

Only exact integers, fractions, JSON parsing, hashes, and finite
combinatorics are used.  The exact direction partition is regenerated by
the authenticated standard-library helper used in the earlier K5 audit.
"""

