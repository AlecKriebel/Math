#!/usr/bin/env python3
"""CP-SAT search for the prescribed-compression Legendre pair of length 333.

For Boolean variables encoding +1 as true, define a difference bit for every
sequence, position, and independent nonzero lag.  The Legendre equation is
equivalent to

    sum_i (a_i XOR a_(i+s)) + sum_i (b_i XOR b_(i+s)) = 334

for ``s=1,...,166``.  The model also fixes all 74 column margins arising from
the conjectural ``C(37,3),D(37,3)`` compression.

The default symmetry mode chooses a lexicographically maximal representative
under the independent dihedral actions generated by shifts through multiples
of 37 and inversion ``i -> -i``.  Every such operation preserves both the LP
equations and this particular fixed compression.

``--mod9-profile`` instead fixes one catalogued exact length-9 row profile.
It replaces the generic compressed products by 18 row cardinalities and
requires ``--symmetry none`` because the generic row actions change the
chosen profile orientation.  This is a restricted exact fiber: any solution
is still a full Legendre pair, but infeasibility concerns only that profile
orbit.

An optional factor-3 compression to length 111 exposes another exact view of
the same equations.  Its entries are sums of three signs, hence belong to
``{-3,-1,1,3}``, and the two compressed PAFs must sum to 662 at lag zero and
-6 at every nonzero lag.  The cheap zero-lag form says exactly 55 of the 222
triples are monochromatic; the full form adds all 55 independent compressed
PAF equations.
"""

