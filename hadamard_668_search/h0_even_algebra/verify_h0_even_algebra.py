"""Exact irreducibility audit for the h=0 half-turn second-digit forms.

The h=0 first-placement affine space splits as X(21) + Y(15) under the
class half-turn.  The even second-digit equations have shape

    F_i(x) + G_i(y) = 0,

while the odd equations have shape

    x^T B_i y + l_i(y) = 0.

This verifier reconstructs those forms from the primary lifting code and
certifies that the relative polar operators of both even pencils generate
the full matrix algebra.  It also checks the same fact after restricting
the X pencil to the canonical y=e_0 odd-equation fiber.
"""

