    with zipfile.ZipFile(temporary, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as zipped:
        for path in sorted(package.rglob("*")):
            if path.is_file():
                entry = zipfile.ZipInfo("dfc_stability_verification/" + path.relative_to(package).as_posix(),
                                        date_time=(2026, 10, 20, 0, 0, 0))
                entry.compress_type = zipfile.ZIP_DEFLATED
                entry.external_attr = 0o100644 << 16
                zipped.writestr(entry, path.read_bytes())
    with zipfile.ZipFile(temporary) as zipped:
        if zipped.testzip() is not None or len(zipped.namelist()) != len(files) + 1:
            raise RuntimeError("ZIP CRC or member-count failure")
    temporary.replace(archive)
    atomic_json(output / "zenodo-deposit.json", {"metadata": metadata, "files": [
        {"path": pdf.name, "name": pdf.name}, {"path": archive.name, "name": archive.name}]})
    artifacts = [{"path": path.name, "bytes": path.stat().st_size, "sha256": sha(path.read_bytes())}
                 for path in (pdf, archive)]
    atomic_json(output / "RELEASE_FILES.json", {"created_utc": now, "files": artifacts})
    receipt = {"status": "BUILT_NOT_PUBLICATION_CLEARANCE", "created_utc": now,
               "generated_directory": str(package), "payload_files": len(files),
               "zip_members": len(files) + 1, "files": artifacts,
               "source_sha256": source_hash,
               "manifest_sha256": sha((package / "MANIFEST.json").read_bytes())}
    atomic_json(output / "PACKAGE_BUILD_RECEIPT.json", receipt)
    print(json.dumps(receipt, indent=2))


