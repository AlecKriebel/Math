#!/usr/bin/env python3
"""Read-only offline custody and finite-control checker; not a proof certificate."""
import argparse
from fractions import Fraction as Q
import hashlib
import json
from pathlib import Path


def require(condition, message):
    if not condition:
        raise ValueError(message)


def equal(actual, expected, message):
    require(actual == expected, message + ': ' + repr(actual) + ' != ' + repr(expected))


def digest(path):
    data = path.read_bytes()
    return {'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}


def power(value, exponent):
    value, exponent = Q(value), Q(exponent)
    if value == 1:
        return Q(1)
    if value == 0 and exponent > 0:
        return Q(0)
    require(exponent.denominator == 1, 'nonrational test fixture power')
    return value ** exponent.numerator


def incident(edges, nvertices):
    return [[i for i, edge in enumerate(edges) if v in edge] for v in range(nvertices)]


def setup(edges, weights, rates, alpha):
    inc = incident(edges, len(rates))
    sums = [sum((power(weights[i], alpha) for i in indices), Q(0)) for indices in inc]
    require(all(s > 0 for s in sums), 'zero denominator fixture')
    return inc, sums


def constructed(edges, b):
    """An exact alpha=2 equilibrium, generated by positive vertex b values."""
    b = list(map(Q, b))
    weights = [1/(b[u]+b[v]) for u, v in edges]
    inc = incident(edges, len(b))
    rates = [b[v]*sum((weights[i]**2 for i in indices), Q(0))
             for v, indices in enumerate(inc)]
    return weights, rates


def direct_jacobian(edges, weights, rates, alpha):
    inc, sums = setup(edges, weights, rates, alpha)
    matrix = [[-Q(i == j) for j in range(len(edges))] for i in range(len(edges))]
    for v, indices in enumerate(inc):
        for i in indices:
            for j in indices:
                if i == j:
                    matrix[i][j] += rates[v]*alpha*power(weights[i], alpha-1)/sums[v]
                matrix[i][j] -= (rates[v]*alpha*power(weights[i], alpha)
                                 *power(weights[j], alpha-1)/sums[v]**2)
    return matrix


def hessian_scaled(edges, weights, rates, alpha):
    inc, sums = setup(edges, weights, rates, alpha)
    require(all(a > 0 for a in weights), 'Hessian only on positive face')
    matrix = [[Q(0) for _ in edges] for _ in edges]
    for i, a in enumerate(weights):
        matrix[i][i] = (alpha-1)*power(a, 1-2*alpha)
    for v, indices in enumerate(inc):
        for i in indices:
            for j in indices:
                matrix[i][j] -= alpha*rates[v]/sums[v]**2
    return matrix


def quadratic(matrix, vector):
    return sum((vector[i]*matrix[i][j]*vector[j]
                for i in range(len(vector)) for j in range(len(vector))), Q(0))


def check_equilibrium_and_congruence(edges, weights, rates, alpha):
    inc, sums = setup(edges, weights, rates, alpha)
    for i, (u, v) in enumerate(edges):
        equal(power(weights[i], alpha)*(rates[u]/sums[u]+rates[v]/sums[v]),
              weights[i], 'equilibrium equation')
    direct = direct_jacobian(edges, weights, rates, alpha)
    scaled = hessian_scaled(edges, weights, rates, alpha)
    transformed = [[power(weights[i], alpha)*power(weights[j], alpha-1)*scaled[i][j]
                    for j in range(len(edges))] for i in range(len(edges))]
    equal(direct, transformed, 'independently differentiated Jacobian/Hessian relation')
    return scaled


def cycle_quantities(edges, weights, rates, alpha, cycle_indices, cycle_vertices):
    inc, sums = setup(edges, weights, rates, alpha)
    dsum = sum((power(weights[i], 1-2*alpha) for i in cycle_indices), Q(0))
    csum = sum((rates[v]/sums[v]**2 for v in cycle_vertices), Q(0))
    require(dsum >= 4*csum, 'weighted cycle inequality')
    return dsum, csum


def finite_path_probability(edges, rates, target):
    require(all(isinstance(n, int) and n >= 1 for n in target),
            'target must consist of positive integer counts')
    counts = [1 for _ in edges]
    inc = incident(edges, len(rates))
    total = sum(rates, Q(0))
    probability = Q(1)
    for i, desired in enumerate(target):
        vertex = edges[i][0]
        for _ in range(desired-1):
            probability *= rates[vertex]/total * Q(counts[i]**2,
                sum(counts[j]**2 for j in inc[vertex]))
            counts[i] += 1
    equal(counts, target, 'finite path reaches requested counts')
    require(probability > 0, 'positive path probability')
    return probability


def rejected(operation):
    try:
        operation()
    except ValueError:
        return True
    return False


def finite_controls():
    results = {}
    alpha = Q(2)
    edges = [(0, 1), (1, 2), (2, 0), (0, 3), (1, 3)]
    weights, rates = constructed(edges, [1, 2, 3, 4])
    matrix = check_equilibrium_and_congruence(edges, weights, rates, alpha)
    dsum, csum = cycle_quantities(edges, weights, rates, alpha, [0, 1, 2], [0, 1, 2])
    cosine = [Q(1), Q(-1, 2), Q(-1, 2), Q(0), Q(0)]
    sine_scaled = [Q(0), Q(1), Q(-1), Q(0), Q(0)]
    fourier = quadratic(matrix, cosine) + Q(3, 4)*quadratic(matrix, sine_scaled)
    equal(fourier, (alpha-1)*dsum-alpha*csum, 'triangle Fourier identity')
    require(fourier > 0, 'unequal-weight attached triangle is unstable')
    results['nonuniform_attached_triangle_fourier_sum'] = str(fourier)
    results['nonuniform_attached_triangle_cycle_slack'] = str(dsum-4*csum)

    inc, sums = setup(edges, weights, rates, alpha)
    b0 = rates[0]/sums[0]
    true_c0 = rates[0]/sums[0]**2
    dropped_c0 = b0/(weights[0]**2+weights[2]**2)
    require(true_c0 < dropped_c0, 'attachment strengthens denominator inequality')
    sign_control = rejected(lambda: equal(matrix, [[-x for x in row] for row in matrix],
                                          'reversed Hessian sign'))
    attachment_control = rejected(lambda: equal(true_c0, dropped_c0, 'dropped attachment'))

    even = [(0, 1), (1, 2), (2, 3), (3, 0), (0, 2), (2, 4)]
    ea, el = constructed(even, [1, 3, 2, 4, 5])
    em = check_equilibrium_and_congruence(even, ea, el, alpha)
    ev = [Q(1), Q(-1), Q(1), Q(-1), Q(0), Q(0)]
    dsum, _ = cycle_quantities(even, ea, el, alpha, [0, 1, 2, 3], [0, 1, 2, 3])
    equal(quadratic(em, ev), (alpha-1)*dsum, 'even cancellation with chord/attachment')
    results['even_cycle_chord_attachment_positive_form'] = str(quadratic(em, ev))

    attached = [(0, 1), (1, 2), (2, 0), (0, 3)]
    aa = [Q(1)]*4
    al = [Q(3, 2), Q(1), Q(1), Q(1, 2)]
    am = check_equilibrium_and_congruence(attached, aa, al, Q(4, 3))
    av = [Q(1), Q(-1, 2), Q(-1, 2), Q(0)]
    bv = [Q(0), Q(1), Q(-1), Q(0)]
    total_form = quadratic(am, av)+Q(3, 4)*quadratic(am, bv)
    equal(total_form, Q(1, 9), 'attached critical-exponent triangle')
    results['attached_triangle_at_4_over_3_positive_form'] = str(total_form)

    triangle = [(0, 1), (1, 2), (2, 0)]
    spectra = {}
    for a in [Q(5, 4), Q(4, 3), Q(3, 2)]:
        tm = check_equilibrium_and_congruence(triangle, [Q(1)]*3, [Q(1)]*3, a)
        jac = direct_jacobian(triangle, [Q(1)]*3, [Q(1)]*3, a)
        transverse = 3*a/4-1
        for vector, eigenvalue in [([Q(1)]*3, Q(-1)),
                                  ([Q(1), Q(-1), Q(0)], transverse),
                                  ([Q(1), Q(0), Q(-1)], transverse)]:
            equal([sum((row[j]*vector[j] for j in range(3)), Q(0)) for row in jac],
                  [eigenvalue*x for x in vector], 'bare triangle exact eigenvector')
        spectra[str(a)] = ['-1', str(transverse), str(transverse)]
    results['bare_triangle_spectra'] = spectra
    below_control = rejected(lambda: require(3*Q(5, 4)/4-1 > 0,
                                             'false universal triangle instability below 4/3'))
    endpoint_control = rejected(lambda: require(3*Q(4, 3)/4-1 < 0,
                                                'false strict stability at 4/3'))

    boundary = direct_jacobian(triangle, [Q(3, 2), Q(3, 2), Q(0)], [Q(1)]*3, Q(2))
    expected = [[Q(-2, 3), Q(-1, 3), Q(0)],
                [Q(-1, 3), Q(-2, 3), Q(0)], [Q(0), Q(0), Q(-1)]]
    equal(boundary, expected, 'full boundary zero-edge direct sum')
    results['boundary_jacobian'] = [[str(x) for x in row] for row in boundary]

    parallel = [(0, 1), (0, 1)]
    pa, pl = constructed(parallel, [2, 3])
    pm = check_equilibrium_and_congruence(parallel, pa, pl, Q(2))
    equal(quadratic(pm, [Q(1), Q(-1)]), Q(250), 'parallel pair cancellation')
    results['parallel_pair_positive_form'] = '250'
    probability = finite_path_probability(triangle, [Q(1), Q(2), Q(3)], [2, 4, 3])
    results['unit_to_counts_2_4_3_path_probability'] = str(probability)
    zero_control = rejected(lambda: finite_path_probability(triangle, [Q(1)]*3, [0, 4, 3]))
    loop_control = rejected(lambda: require(not any(u == v for u, v in [(0, 0)]),
                                            'single loop is not a forest'))
    controls = {'reversed_hessian_sign': sign_control, 'dropped_attachment': attachment_control,
                'odd_cycle_below_threshold': below_control, 'critical_triangle_strict_stability': endpoint_control,
                'zero_count_reachability': zero_control, 'loop_as_forest': loop_control}
    require(all(controls.values()), 'a negative control was not rejected')
    results['negative_controls_rejected'] = controls
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', required=True)
    parser.add_argument('--seal', required=True)
    args = parser.parse_args()
    root = Path(args.root).resolve()
    seal_path = Path(args.seal).resolve()
    require(root not in seal_path.parents, 'external seal must be outside payload root')
    seal = json.loads(seal_path.read_text())
    manifest_path = root/'public/MANIFEST.json'
    equal(digest(manifest_path), seal['manifest'], 'external manifest seal')
    manifest = json.loads(manifest_path.read_text())
    equal(manifest['head'], 'bacae693a1f2a33c89565b0bd716620885831289', 'actual head')
    equal(manifest['base'], 'f6caddda8f8be2cdb3e91494325d8f7f365bc3fc', 'actual base')
    require(manifest['foundation_proof_certificate'] is False, 'foundation disclaimer')
    paths = [entry['path'] for entry in manifest['entries']]
    equal(len(paths), len(set(paths)), 'unique manifest paths')
    actual_files = {str(p.relative_to(root)) for p in root.rglob('*') if p.is_file()}
    equal(actual_files, set(paths) | {'public/MANIFEST.json'}, 'complete payload file inventory')
    for entry in manifest['entries']:
        relative = Path(entry['path'])
        require(not relative.is_absolute() and '..' not in relative.parts, 'unsafe manifest path')
        candidate = root/relative
        require(root in candidate.resolve().parents, 'manifest path escapes root')
        require(not candidate.is_symlink(), 'symlink payload disallowed')
        equal(digest(candidate), {'bytes': entry['bytes'], 'sha256': entry['sha256']},
              'bound payload '+entry['path'])
    equal(digest(root/'public/verify_forest.py'), seal['verifier'], 'external verifier seal')
    expected_head = {'ACCEPTANCE.json', 'MANIFEST.json', 'MATHEMATICAL_AUDIT.md', 'PROOF.md',
                     'README.md', 'SOURCE_METADATA.json', 'SOURCE_REVIEW.md', 'STATUS.json'}
    equal(set(p.name for p in (root/'private/head').iterdir()), expected_head,
          'exact eight authored captures')
    captured = json.loads((root/'private/head/MANIFEST.json').read_text())
    for entry in captured['entries']:
        equal(digest(root/'private/head'/entry['file']),
              {'bytes': entry['bytes'], 'sha256': entry['sha256']}, 'authored manifest member')
    controls = finite_controls()
    print(json.dumps({'status': 'PASS', 'read_only': True,
                      'foundation_proof_certificate': False,
                      'manifest_sha256': seal['manifest']['sha256'],
                      'bound_payload_files': len(paths), 'controls': controls}, indent=2, sort_keys=True))


if __name__ == '__main__':
    main()
