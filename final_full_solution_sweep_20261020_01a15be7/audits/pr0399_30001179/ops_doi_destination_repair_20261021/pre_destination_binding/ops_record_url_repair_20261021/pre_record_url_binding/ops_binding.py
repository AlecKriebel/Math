def sha(data):
    return hashlib.sha256(data).hexdigest()


def digest(value):
    return sha(json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(',', ':')).encode())


def strict_json(data):
    def object_pairs(pairs):
        result={}
        for key,value in pairs:
            if key in result:raise RuntimeError('Duplicate JSON key: '+key)
            result[key]=value
        return result
    return json.loads(data,object_pairs_hook=object_pairs)


def safe_file(root, name):
    if (not isinstance(name,str) or not name or '\\' in name or '\x00' in name
            or ':' in name or any(part in {'','.','..'} for part in name.split('/'))):
        raise RuntimeError('Unsafe artifact path: ' + str(name))
    p = PurePosixPath(name)
    if (p.is_absolute() or p.as_posix() != name or root.is_symlink()
            or any((root.joinpath(*p.parts[:i])).is_symlink() for i in range(1, len(p.parts)+1))):
        raise RuntimeError('Unsafe artifact path: ' + str(name))
    return root / name


def verify_entries(root, entries):
    if not isinstance(entries, list) or not entries:
        raise RuntimeError('Absent bound artifacts')
    seen = set()
    for entry in entries:
        if (not isinstance(entry,dict) or set(entry)!={'path','bytes','sha256'}
                or type(entry['bytes']) is not int or entry['bytes'] < 0
                or not isinstance(entry['sha256'],str) or not re.fullmatch('[0-9a-f]{64}',entry['sha256'])):
            raise RuntimeError('Invalid exact artifact binding schema')
        name = entry['path']
        path=safe_file(root,name)
        if name in seen or not path.is_file():
            raise RuntimeError('Duplicate or non-file bound artifact')
        seen.add(name)
        data = path.read_bytes()
        if len(data) != entry['bytes'] or sha(data) != entry['sha256']:
            raise RuntimeError('Bound artifact changed: ' + name)
    return seen


def intent_json(path, value):
    # Exclusive creation and fsync make an uncertain mutation durably visible.
    # Existing intents require human/root reconciliation, including absent outcomes.
    data=(json.dumps(value,ensure_ascii=False,sort_keys=True,indent=2)+'\n').encode()
    path.parent.mkdir(parents=True,exist_ok=True)
    fd=os.open(path,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
    try:
        with os.fdopen(fd,'wb') as stream:
            stream.write(data);stream.flush();os.fsync(stream.fileno())
        directory=os.open(path.parent,os.O_RDONLY)
        try:os.fsync(directory)
        finally:os.close(directory)
    except BaseException:
        # Preserve even a partial/uncertain intent; never remove it for a retry.
        raise


