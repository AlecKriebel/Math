def check_zip(data):
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        names = archive.namelist()
        if len(names) != 82 or len(set(names)) != 82 or archive.testzip() is not None:
            raise RuntimeError('ZIP inventory, duplicates or CRC invalid')
        for info in archive.infolist():
            safe_file(Path('/synthetic'), info.filename)
            if info.is_dir() or (info.external_attr >> 16 & 0o170000) == 0o120000:
                raise RuntimeError('Directory or symlink ZIP member')
        listing = strict_json(archive.read(PREFIX + 'FILES.json'))
        if (not isinstance(listing,dict) or set(listing)!={'schema','files'}
                or type(listing['schema']) is not int or listing['schema']!=1):
            raise RuntimeError('PR399 FILES.json exact schema1 object required')
        declared = listing['files']
        if not isinstance(declared, list) or len(declared) != 81:
            raise RuntimeError('PR399 manifest must be a list of 81 payloads')
        if any(not isinstance(v,dict) or set(v)!={'path','bytes','sha256'}
                or type(v['bytes']) is not int or v['bytes']<0
                or not isinstance(v['sha256'],str) or not re.fullmatch('[0-9a-f]{64}',v['sha256']) for v in declared):
            raise RuntimeError('Malformed ZIP exact payload binding')
        keys = [v['path'] for v in declared]
        if len(set(keys)) != 81 or set(names) != {PREFIX+'FILES.json'} | {PREFIX+p for p in keys}:
            raise RuntimeError('ZIP manifest member set differs')
        for item in declared:
            safe_file(Path('/synthetic'), item['path'])
            body = archive.read(PREFIX + item['path'])
            if len(body) != item['bytes'] or sha(body) != item['sha256']:
                raise RuntimeError('ZIP manifest payload changed: ' + item['path'])
        return {'members': 82, 'all_manifest_payloads_verified': 81, 'zip_crc_safe_unique_pass': True}


