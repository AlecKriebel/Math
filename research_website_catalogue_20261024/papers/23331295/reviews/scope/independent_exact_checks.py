def clean(p):
 return {k: Fraction(v) for k, v in p.items() if v}

def add(p, q):
 out = dict(p)
 for k, c in q.items():
  out[k] = out.get(k, 0) + c
 return clean(out)

def scale(p, c):
 return clean({k: v*c for k, v in p.items()})

def mul(p, q):
 out = {}
 for i, c in p.items():
  for j, d in q.items():
   out[i+j] = out.get(i+j, 0) + c*d
 return clean(out)

def power(p, n):
 out = {0: Fraction(1)}
 for _ in range(n):
  out = mul(out, p)
 return out

def value(p, t):
 return sum(c*t**k for k, c in p.items())

def difference(p):
 shifted = {}
 for k, c in p.items():
  for j in range(k+1):
   shifted[j] = shifted.get(j, 0) + c*comb(k, j)
 return add(shifted, scale(p, -1))

def binomial_polynomial(r):
 out = {0: Fraction(1)}
 for j in range(r):
  out = mul(out, {1: Fraction(1), 0: Fraction(-j)})
 return scale(out, Fraction(1, factorial(r)))

def newton(p, d):
 out = {}
 current = p
 for r in range(d+1):
  out = add(out, scale(binomial_polynomial(r), value(current, 0)))
  current = difference(current)
 return out

