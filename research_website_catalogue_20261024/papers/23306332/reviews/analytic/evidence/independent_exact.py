"""Fresh exact controls, independently written for the analytic review.

No submitted code is imported. Finite controls supplement the proof review.
All mathematical predicates use rational arithmetic, including comparisons
against Phi(D), evaluated by sign-aware exact squaring rather than floats.
"""
from fractions import Fraction as Q
from collections import Counter
from itertools import product
import json

counts = Counter()
def check(test, label):
    if not test:
        raise AssertionError(label)
    counts[label] += 1

def plus(z, w): return (z[0]+w[0], z[1]+w[1])
def minus(z, w): return (z[0]-w[0], z[1]-w[1])
def times(z, w): return (z[0]*w[0]-z[1]*w[1], z[0]*w[1]+z[1]*w[0])
def scale(t, z): return (t*z[0], t*z[1])
def pair(z, w): return z[0]*w[0]+z[1]*w[1]
def square(z): return pair(z,z)
def quotient(z,w):
    r=square(w)
    return ((z[0]*w[0]+z[1]*w[1])/r,(z[1]*w[0]-z[0]*w[1])/r)

def phi_ge(d,k):
    """Exactly decide sqrt((sqrt(x*x+y*y)+x)/2) >= rational k."""
    if k <= 0: return True
    h=2*k*k-d[0]
    return h <= 0 or square(d) >= h*h

def coefficient(a,d): return a,scale(Q(1,4),minus(times(a,a),d))
def disc(a,b): return minus(times(a,a),scale(4,b))
def chart(a,b):
    x,y=a; u,v=b
    U=u+y*y/4; V=v-x*y/2
    return x>=0 and U>=0 and V*V<=x*x*U
def flatten(a,b): return (*a,*b)
def dot(v,w): return sum((x*y for x,y in zip(v,w)),Q(0))
def norm2(v): return dot(v,v)

# Complete rational-root grid, including coincident imaginary roots, double
# roots away from the axis, opposite half-planes, and arbitrary complex data.
grid=[Q(-2),Q(-1,2),Q(0),Q(1,3),Q(2)]
for r1,i1,r2,i2 in product(grid,repeat=4):
    z1,z2=(r1,i1),(r2,i2)
    a=scale(-1,plus(z1,z2)); b=times(z1,z2)
    check(chart(a,b)==(max(r1,r2)<=0),'chart_vs_known_complex_roots')
    check(disc(a,b)==times(minus(z1,z2),minus(z1,z2)),'discriminant_known_roots')

# Boundary conditions are essential: omitting x>=0 wrongly accepts z^2-z+1;
# omitting U>=0 at x=0 wrongly accepts z^2-1. Conjugate and double-root
# boundary cases are present in the complete grid above.
check(not chart((Q(-1),Q(0)),(Q(1),Q(0))),'drop_x_nonnegative_mutant_rejected')
check(not chart((Q(0),Q(0)),(Q(-1),Q(0))),'drop_U_nonnegative_mutant_rejected')
check(chart((Q(0),Q(-2)),(Q(-1),Q(0))),'double_imaginary_root_boundary')
check(chart((Q(0),Q(0)),(Q(1),Q(0))),'distinct_imaginary_roots_boundary')

# Exact derivative computation in all real directions from the active root.
# The denominator is computed as p'(lambda), not inserted as a quoted normal.
one=(Q(1),Q(0)); eye=(Q(0),Q(1))
for j in range(1,65):
    t=Q(1,j+1)
    a=(t*t,Q(0)); b=(t*t,t**3); lam=(Q(0),-t)
    other=(-t*t,t)
    check(plus(times(lam,lam),plus(times(a,lam),b))==(0,0),'active_root_exact')
    check(plus(lam,other)==scale(-1,a) and times(lam,other)==b,'path_factorization')
    denominator=plus(scale(2,lam),a)
    gamma=Q(2)/(t*(t*t+4))
    gradient=[]
    for exponent in (2,1,0):
        power=times(lam,lam) if exponent==2 else lam if exponent==1 else one
        for direction in (one,eye):
            gradient.append(quotient(scale(-1,times(power,direction)),denominator)[0])
    expected=[t**3/2,-t*t,-t,-t*t/2,-t/2,Q(1)]
    check(gradient==[gamma*x for x in expected],'six_real_implicit_derivatives')
    displacement=[t*t,Q(0),t*t,t**3]
    check(norm2(displacement)==2*t**4+t**6,'path_quartic_squared_distance')
    check(chart(a,b),'path_closed_stable')
    # Deliberate sign mutant: the displayed active normal must be outward.
    check(expected[-1]==1 and gradient[-1]>0,'negative_normal_sign_mutant_rejected')

# Rational SPD matrices are generated by G=A^T A, with triangular A of
# nonzero rational diagonal. This covers cross-coordinate controls without
# relying on an approximate eigenvalue calculation.
metric_rows=[]
for dim in (4,6,5,7):
    A=[[Q(0) for _ in range(dim)] for _ in range(dim)]
    for i in range(dim):
        for j in range(i,dim):
            A[i][j]=Q((-1)**(i+j)*(i+2*j+1),i+j+2) if j!=i else Q(i+1,3)
    G=[[sum((A[k][i]*A[k][j] for k in range(dim)),Q(0)) for j in range(dim)] for i in range(dim)]
    coeffdim=dim if dim in (4,6) else dim-1
    e=[Q(0)]*dim; f=[Q(0)]*dim
    offset=coeffdim-4
    e[offset]=e[offset+2]=Q(1); f[offset+3]=Q(1)
    bilinear=lambda u,v: sum((u[i]*G[i][j]*v[j] for i in range(dim) for j in range(dim)),Q(0))
    E,C,F=bilinear(e,e),bilinear(e,f),bilinear(f,f)
    K=E+2*abs(C)+F
    check(E>0 and F>0,'SPD_leading_quartic_positive')
    tau=Q(1,53)
    t=min(Q(1,2),tau/K)
    c=[t*t*x+t**3*y for x,y in zip(e,f)]
    check(bilinear(c,c)==t**4*(E+2*t*C+t*t*F),'mixed_metric_quartic_identity')
    check(bilinear(c,c)<=K*t**4,'metric_upper_bound')
    check(bilinear(c,c)-2*tau*t**3<0,'fixed_tau_metric_distance_improves')
    metric_rows.append({'dimension':dim,'tau':str(tau),'t':str(t),'K':str(K),'distance_difference':str(bilinear(c,c)-2*tau*t**3)})

# An independent mixed height metric has block [[1,2/5],[2/5,1]],
# eigenvalues 3/5 and 7/5. The horizontal normal covector has a tilted
# representing vector, and its metric pairing remains the original support.
v=(Q(25,21),Q(-10,21))
check((v[0]+Q(2,5)*v[1],Q(2,5)*v[0]+v[1])==(1,0),'mixed_height_inverse_metric')
check(v[1]!=0,'horizontal_covector_tilt_control')

# Sign-aware radical controls, including both axes and approaches to both
# sides of the negative ray. All points satisfy |D| <= delta exactly.
for M in (Q(1),Q(7),Q(10000)):
    delta=1/(16*M*M)
    # Phi >= dist(D,L)/(2 sqrt(delta)) = 2 M dist for this delta.
    for u,v in product([Q(-1),Q(-1,2),Q(0),Q(1,2),Q(1)],repeat=2):
        d=(delta*u/2,delta*v/2)
        # When Re D>=0, distance involves a radical; the weaker
        # coefficient support below is checked directly by exact squaring.
        if d[0]<0:
            check(phi_ge(d,2*M*abs(d[1])),'negative_ray_distance_lower_bound')
        else:
            # Phi^2 >= 4 M^2 |D|^2; same exact radical comparison.
            h=8*M*M*square(d)-d[0]
            check(h<=0 or square(d)>=h*h,'right_halfplane_distance_lower_bound')
    for k in range(1,30):
        d=(-delta/2,(-1)**k*delta/Q(2**(k+1)))
        check(phi_ge(d,2*M*abs(d[1])),'near_ray_distance_lower_bound')

    for s in (Q(0),delta/2):
        dx=(-s,Q(0))
        for q in ((M,Q(0)),(Q(0),M),(Q(0),-M),(Q(0),Q(0))):
            if s and q[0]: continue
            if s: check(4*s*square(q)<=1,'on_ray_subgradient_membership')
            for k in range(1,30):
                ax=(delta/Q(k+3),-delta/Q(k+4))
                ay=(-delta/Q(k+2),delta/Q(k+5))
                dy=(delta*Q((-1)**k,3),delta*Q((-1)**(k//2),4))
                _,bx=coefficient(ax,dx); _,by=coefficient(ay,dy)
                da=minus(ay,ax); db=minus(by,bx)
                check(disc(ax,bx)==dx and disc(ay,by)==dy,'diffeomorphism_exact_inverse')
                jd=minus(scale(2,times(ax,da)),scale(4,db))
                check(minus(dy,dx)==plus(jd,times(da,da)),'exact_discriminant_Taylor_identity')
                # Directly test alpha_y-alpha_x-v.Delta+(M/2)|Delta|^2 >=0.
                d2=square(da)+square(db)
                rhs=pair(q,jd)-M*d2
                check(phi_ge(dy,rhs),'bounded_subgradient_coefficient_support')
                check(phi_ge(dy,pair(q,minus(dy,dx))),'ray_normal_scalar_support')

# Exact adverse curvature and negative controls: omitting the quadratic
# discriminant correction, or using a too-small curvature constant, fails.
mutants=[]
for M in (Q(1),Q(7),Q(10000)):
    h=Q(1,1000)
    ax,dx=(Q(0),Q(0)),(Q(0),Q(0)); ay=(Q(0),h)
    _,bx=coefficient(ax,dx); _,by=coefficient(ay,dx)
    da,db=minus(ay,ax),minus(by,bx)
    q=(M,Q(0)); jd=minus(scale(2,times(ax,da)),scale(4,db))
    # True alpha difference = 0 and v.Delta = M*h^2/2.
    deficit=-pair(q,jd)/2
    d2=square(da)+square(db)
    check(deficit==-M*h*h/2,'adverse_curvature_exact_deficit')
    check(deficit+M*d2/2==M*h**4/32,'claimed_curvature_exact_slack')
    check(deficit+(M/2)*d2/2<0,'half_curvature_mutant_rejected')
    check(not phi_ge(dx,pair(q,jd)),'omit_quadratic_correction_mutant_rejected')
    mutants.append({'M':str(M),'h':str(h),'true_deficit':str(deficit),'half_curvature_slack':str(deficit+M*d2/4)})

# Off-ray gradient formula with D=(r+is)^2 has Phi(D)=r (r>0).
for r,s in product([Q(1,2),Q(1,100),Q(1,1000000)],[Q(-2),Q(-1,2),Q(0),Q(1,3),Q(2)]):
    d=times((r,s),(r,s)); radius=r*r+s*s
    gradient=(r/(2*radius),s/(2*radius))
    check(4*radius*square(gradient)==1,'off_ray_gradient_norm_identity')
    check(phi_ge(d,r) and not phi_ge(d,r+Q(1,1000000000000000000)),'exact_Phi_radical_branch')

print(json.dumps({'arithmetic':'exact rational; sign-aware radical squaring',
    'assertions':sum(counts.values()),'counts':dict(sorted(counts.items())),
    'metric_controls':metric_rows,'negative_controls':mutants,
    'finite_controls_only':True,'submitted_code_imported':False},indent=2,sort_keys=True))
