"""Fresh permutation and bit-polynomial checks, importing no author modules."""
import collections,itertools,json,math
from pathlib import Path
from datetime import datetime,timezone


def parts(n,maximum=None):
    if n==0:yield ();return
    if maximum is None:maximum=n
    for k in range(min(maximum,n),0,-1):
        for rest in parts(n-k,k):yield (k,)+rest


def representative(partition):
    p=[];offset=0
    for length in partition:
        p.extend([offset+(j+1)%length for j in range(length)]);offset+=length
    return tuple(p)


def inv(p):
    back=[0]*len(p)
    for k,v in enumerate(p):back[v]=k
    return tuple(back)


def comm(a,t):
    backa=inv(a);backt=inv(t)
    return tuple(backa[backt[a[t[x]]]] for x in range(len(a)))


def allowed(b,c,t):
    # Build every group orbit by explicit breadth-first search; no union/find.
    unseen=set(range(len(t)))
    while unseen:
        seed=min(unseen);orbit={seed};queue=collections.deque([seed])
        while queue:
            x=queue.popleft()
            for generator in (c,t):
                y=generator[x]
                if y not in orbit:orbit.add(y);queue.append(y)
        if any(b[x] in orbit for x in orbit):return False
        unseen-=orbit
    return True


def census(d):
    identity=tuple(range(d));counts=collections.Counter();tested=0
    for cycle_partition in parts(d):
        t=representative(cycle_partition)
        for top in itertools.permutations(range(d)):
            tested+=1;seq=[top];seen={top}
            while seq[-1]!=identity:
                nxt=comm(seq[-1],t)
                if nxt in seen:break
                seq.append(nxt);seen.add(nxt)
            if seq[-1]!=identity:continue
            ell=len(seq)-1
            for m in (ell,ell+1):
                if m<2:continue
                b=seq[m-2];c=seq[m-1] if m-1<len(seq) else identity
                if allowed(b,c,t):counts[m]+=1
    assert tested==math.factorial(d)*len(list(parts(d)))
    return {'degree':d,'pairs':tested,'counts':dict(sorted(counts.items())),'permitted_ranks':sorted(counts)}


def uniform(m):
    n=1
    while n<m-1:n*=2
    mask=(1<<n)-1
    def shift(v):return ((v>>1)|((v&1)<<(n-1)))&mask
    def delta(v):return v^shift(v)
    vector=1
    for _ in range(n-(m-1)):vector=delta(vector)
    top=vector;images={m:vector}
    for i in range(m-1,0,-1):vector=delta(vector);images[i]=vector
    assert images[1]==0 and images[2]==mask
    # Check group relations on the 2N-point affine action directly.
    t=tuple(2*((j+1)%n)+bit for j in range(n) for bit in range(2))
    b=lambda v:tuple(2*j+(bit^((v>>j)&1)) for j in range(n) for bit in range(2))
    actual={i:b(v) for i,v in images.items()}
    for i in range(2,m+1):assert comm(actual[i],t)==actual[i-1]
    assert comm(actual[1],t)==tuple(range(2*n))
    p=tuple(range(2*n))
    for _ in range(n):
        assert all(actual[2][p[x]]!=x for x in range(2*n))
        p=tuple(t[p[x]] for x in range(2*n))
    # The orbit of 0 under top flip and t is all of Omega.
    reached={0};queue=collections.deque([0])
    while queue:
        x=queue.popleft()
        for g in (t,actual[m]):
            y=g[x]
            if y not in reached:reached.add(y);queue.append(y)
    assert len(reached)==2*n
    # Dimension of the cyclic F2 shift-module generated by top.
    pivots={};v=top
    for _ in range(n):
        w=v
        while w:
            h=w.bit_length()-1
            if h in pivots:w^=pivots[h]
            else:pivots[h]=w;break
        v=shift(v)
    assert len(pivots)==m-1
    return {'rank':m,'degree':2*n,'finite_image_order':n*(2**(m-1)),'nilpotency_class':m-1,'module_dimension':len(pivots)}

