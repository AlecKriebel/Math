#!/usr/bin/env python3
"""Evaluate the s-membership proof directly with ring-unit powers by squaring.
No group collection or Lie subspace search is performed here.
"""
from pathlib import Path
import json,hashlib,time
root=Path(__file__).parent;craw=(root/'rank5_lie_certificate.json').read_bytes();sraw=(root/'rank5_s_membership_slp.json').read_bytes();C=json.loads(craw);S=json.loads(sraw);p=C['prime'];degree=C['class_bound'];one={'':1}
def mul(a,b):
    out={}
    for x,u in a.items():
        for y,v in b.items():
            if len(x)+len(y)<=degree:out[x+y]=(out.get(x+y,0)+u*v)%p
    return {x:v for x,v in out.items() if v}
def power(a,n):
    out=dict(one)
    while n:
        if n&1:out=mul(out,a)
        a=mul(a,a);n//=2
    return out
def exponential(a):
    result=dict(one);term=dict(one);factorial=1
    for k in range(1,degree+1):
        term=mul(term,a);factorial=factorial*k%p;z=pow(factorial,-1,p)
        for w,v in term.items():
            result[w]=(result.get(w,0)+z*v)%p
            if not result[w]:del result[w]
    return result
start=time.time();values=[];forms=[];seed_counts={}
for index,node in enumerate(S['proof_nodes']):
    op=node['op']
    if op=='seed':
        kind=node['kind'];j=node['index'];seed_counts[kind]=seed_counts.get(kind,0)+1
        if kind=='ideal_exponential':value=exponential(C['ideal_basis'][j]);form='H'
        elif kind=='L_generator_exponential':value=exponential(C['L_generator_logs'][j]);form='H'
        elif kind=='s':assert j==0;value=exponential({'x':1});form='H_times_s'
        else:raise AssertionError(kind)
    elif op=='pow':
        a=node['arg'];assert a<index and forms[a]=='H';n=node['exponent'];assert 0<=n<p
        value=power(values[a],n);form='H'
    elif op=='multiply':
        a,b=node['left'],node['right'];assert a<index and b<index
        assert forms[a]=='H' and forms[b] in ('H','H_times_s')
        value=mul(values[a],values[b]);form=forms[b]
    else:raise AssertionError(op)
    values.append(value);forms.append(form)
last=S['identity_node'];assert last==len(values)-1 and forms[last]=='H_times_s' and values[last]==one
assert seed_counts['s']==1
out={'status':'PASS','certificate_sha256':hashlib.sha256(craw).hexdigest(),'membership_slp_sha256':hashlib.sha256(sraw).hexdigest(),'proof_nodes':len(values),'seed_counts':seed_counts,'identity':values[last],'word_shape':'h*s=1 with h generated by L-generator exponentials and exp(I) seeds','conclusion':'q(s) is in q(L5), so the explicit no-self-crossing cover inter-osculates and is not special','elapsed_seconds':time.time()-start}
(root/'rank5_s_membership_verification.json').write_text(json.dumps(out,indent=2)+'\n');print(json.dumps(out,indent=2))
