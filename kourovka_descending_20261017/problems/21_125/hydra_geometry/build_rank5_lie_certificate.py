#!/usr/bin/env python3
"""Exact certificate for a self-intersection-free finite-quotient partial, rank5 only."""
from nilpotent_lie_filter import P,add,scalar,prod,exp,log,inverse,bracket,Span
from pathlib import Path
import json,hashlib

def key(w):return (len(w),w)
def dual(span,remainder):
    w=min(remainder,key=key);f={w:1}
    for pivot,row in sorted(span.rows.items(),key=lambda z:key(z[0]),reverse=True):
        val=-sum(c*f.get(q,0) for q,c in row.items() if q!=pivot)%P
        if val:f[pivot]=val
        elif pivot in f:del f[pivot]
    return f

def build():
    m,c=5,10;x={'x':1};y={'y':1};s=exp(x,c);top=exp(y,c)
    aa=[s]+[None]*m;aa[m]=top
    for i in range(m,1,-1):aa[i-1]=prod(prod(inverse(aa[i],c),s,c),aa[i],c)
    r=log(prod(prod(prod(inverse(s,c),inverse(aa[1],c),c),s,c),aa[1],c),c)
    ideal=Span();iq=[]
    k=ideal.insert(r)
    if k:iq.append(k)
    for b in iq:
        for z in (x,y):
            k=ideal.insert(bracket(z,b,c))
            if k:iq.append(k)
    gs=[log(aa[1],c)]+[log(prod(prod(aa[i],s,c),inverse(aa[i],c),c),c) for i in range(2,m+1)]
    W=Span()
    for b in iq:W.insert(b)
    wq=[]
    for g in gs:
        k=W.insert(g)
        if k:wq.append(k)
    for b in wq:
        for g in gs:
            k=W.insert(bracket(g,b,c))
            if k:wq.append(k)
    R=Span();rq=[]
    for z in (x,y):rq.append(R.insert(z))
    for b in rq:
        for z in (x,y):
            k=R.insert(bracket(z,b,c))
            if k:rq.append(k)
    logs=[log(a,c) for a in aa]
    fs=[]
    for j in range(2,m+1):
        rem=W.reduce(logs[j]);assert rem
        f=dual(W,rem)
        assert all(sum(f.get(k,0)*v for k,v in b.items())%P==0 for b in W.rows.values())
        val=sum(f.get(k,0)*v for k,v in logs[j].items())%P;assert val
        fs.append({'alpha_index':j,'functional':f,'nonzero_value':val})
    return {'scope':'Rank5 canonical complex only: no self-intersections in a finite BCH p-group quotient cover. No inter-osculation, specialness, novelty, or full-solution claim.','prime':P,'rank':m,'class_bound':c,'ambient_description':'Lie subalgebra generated by x,y in truncated noncommutative F101<x,y> to degree10, modulo Lie ideal generated by log(s^-1 alpha1^-1 s alpha1). BCH group.','ambient_lie_dimension':len(R.rows),'relation_ideal_dimension':len(ideal.rows),'quotient_dimension':len(R.rows)-len(ideal.rows),'W_dimension':len(W.rows),'group_order_upper_bound':f'{P}^{len(R.rows)-len(ideal.rows)}','log_s':x,'log_top':y,'alpha_logs':logs[1:],'relator_log':r,'L_generator_logs':gs,'R_basis':list(R.rows.values()),'ideal_basis':list(ideal.rows.values()),'W_basis':list(W.rows.values()),'dual_separation_certificates':fs}
if __name__=='__main__':
    out=Path(__file__).with_name('rank5_lie_certificate.json');cert=build();out.write_text(json.dumps(cert,indent=2,sort_keys=True)+'\n')
    print(json.dumps({'file':str(out),'bytes':out.stat().st_size,'sha256':hashlib.sha256(out.read_bytes()).hexdigest(),'dimensions':[cert[k] for k in ('ambient_lie_dimension','relation_ideal_dimension','quotient_dimension','W_dimension')],'separating_values':[(r['alpha_index'],r['nonzero_value'],len(r['functional'])) for r in cert['dual_separation_certificates']]}))
