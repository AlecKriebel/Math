#!/usr/bin/env python3
"""Independent exact check: Cartan-generated roots, Gaussian flat closures.

Does not import the author's program or root list.  Field elements use a
single integer denominator in Q(sqrt(5)), with normalization by integer gcd.
The complete root systems are generated by simple reflection matrices from
the F4 and H4 Coxeter Cartan matrices.  Flat equality is Gaussian elimination,
not wedges/minors.  Output includes all incidence types and two independent
formulations of the cube arithmetic.
"""
from dataclasses import dataclass
from fractions import Fraction
from math import gcd
from collections import Counter
from itertools import combinations
from pathlib import Path
import argparse, json, time

@dataclass(frozen=True)
class K:
    a: int = 0
    b: int = 0
    d: int = 1
    def __post_init__(self):
        a,b,d=self.a,self.b,self.d
        if not d: raise ZeroDivisionError()
        if d<0: a,b,d=-a,-b,-d
        g=gcd(gcd(abs(a),abs(b)),d)
        object.__setattr__(self,'a',a//g)
        object.__setattr__(self,'b',b//g)
        object.__setattr__(self,'d',d//g)
    def __bool__(self): return bool(self.a or self.b)
    def __add__(self, other):
        if isinstance(other,int):other=K(other)
        return K(self.a*other.d+other.a*self.d,
                 self.b*other.d+other.b*self.d,self.d*other.d)
    __radd__=__add__
    def __neg__(self): return K(-self.a,-self.b,self.d)
    def __sub__(self,other): return self+-other
    def __mul__(self,other):
        if isinstance(other,int):other=K(other)
        return K(self.a*other.a+5*self.b*other.b,
                 self.a*other.b+self.b*other.a,self.d*other.d)
    __rmul__=__mul__
    def inv(self):
        if not self: raise ZeroDivisionError()
        return K(self.a*self.d,-self.b*self.d,self.a*self.a-5*self.b*self.b)
    def __truediv__(self,other): return self*other.inv()
    def raw(self): return [self.a,self.b,self.d]

ZERO=K(); ONE=K(1); PHI=K(1,1,2)

def rref(rows):
    rows=[list(x) for x in rows]; pos=0
    for col in range(4):
        pivot=next((i for i in range(pos,len(rows)) if rows[i][col]),None)
        if pivot is None:continue
        rows[pos],rows[pivot]=rows[pivot],rows[pos]
        fac=rows[pos][col].inv()
        rows[pos]=[x*fac for x in rows[pos]]
        for i in range(len(rows)):
            if i!=pos and rows[i][col]:
                fac=rows[i][col]
                rows[i]=[x-fac*y for x,y in zip(rows[i],rows[pos])]
        pos+=1
        if pos==len(rows):break
    return tuple(tuple(x) for x in rows[:pos])

def contains(basis,row):
    row=list(row)
    for b in basis:
        col=next(i for i,v in enumerate(b) if v)
        c=row[col]
        if c:row=[x-c*y for x,y in zip(row,b)]
    return not any(row)

def roots(kind):
    simple=tuple(tuple(ONE if i==j else ZERO for j in range(4)) for i in range(4))
    if kind in {'A4','B4'}:
        cartan=((K(2),K(-1),ZERO,ZERO),
                (K(-1),K(2),K(-1),ZERO),
                (ZERO,K(-1),K(2),K(-2) if kind=='B4' else K(-1)),
                (ZERO,ZERO,K(-1),K(2)))
    elif kind=='F4':
        cartan=((K(2),K(-1),ZERO,ZERO),
                (K(-1),K(2),K(-2),ZERO),
                (ZERO,K(-1),K(2),K(-1)),
                (ZERO,ZERO,K(-1),K(2)))
    elif kind=='H4':
        cartan=((K(2),-PHI,ZERO,ZERO),
                (-PHI,K(2),K(-1),ZERO),
                (ZERO,K(-1),K(2),K(-1)),
                (ZERO,ZERO,K(-1),K(2)))
    else:raise ValueError(kind)
    def reflection(i,v):
        w=list(v);w[i]=w[i]-sum(c*x for c,x in zip(cartan[i],v));return tuple(w)
    expected={'F4':(3,4,3),'H4':(5,3,3),'A4':(3,3,3),'B4':(3,3,4)}[kind]
    # Independently certify every pair order of the simple-reflection
    # matrices; a first return, not merely a power, is checked.
    for i,j in combinations(range(4),2):
        m=expected[i] if j==i+1 else 2
        images=list(simple)
        for k in range(1,m+1):
            images=[reflection(i,reflection(j,v)) for v in images]
            assert (tuple(images)==simple)==(k==m)
    pending=list(simple); seen=set(pending)
    while pending:
        v=pending.pop()
        for i in range(4):
            w=reflection(i,v)
            if w not in seen:seen.add(w);pending.append(w)
        if len(seen)>10000:raise RuntimeError('Unexpected infinite root set')
    lines={rref((v,))[0] for v in seen}
    lines=sorted(lines,key=lambda row:tuple((x.a,x.b,x.d) for x in row))
    assert len(seen)=={'F4':48,'H4':120,'A4':20,'B4':32}[kind]
    assert len(lines)=={'F4':24,'H4':60,'A4':10,'B4':16}[kind]
    return lines,cartan,len(seen)

def compute(kind):
    started=time.time(); vectors,cartan,nroot=roots(kind);n=len(vectors)
    two={rref((a,b)) for a,b in combinations(vectors,2)}
    assert all(len(s)==2 for s in two)
    three={rref((*s,v)) for s in two for v in vectors if not contains(s,v)}
    assert all(len(s)==3 for s in three)
    flat2={tuple(i for i,v in enumerate(vectors) if contains(s,v)) for s in two}
    flat3={tuple(i for i,v in enumerate(vectors) if contains(s,v)) for s in three}
    assert len(flat2)==len(two) and len(flat3)==len(three)
    lsets=[frozenset(x) for x in flat2]; psets=[frozenset(x) for x in flat3]
    # Every pair/triple basis is contained in a unique flat of its rank.
    pair_count=sum(len(x)*(len(x)-1)//2 for x in flat2)
    assert pair_count==n*(n-1)//2
    independent_triples=sum(1 for a,b,c in combinations(vectors,3) if len(rref((a,b,c)))==3)
    triple_count=sum(len(p)*(len(p)-1)*(len(p)-2)//6-
                     sum(len(l)*(len(l)-1)*(len(l)-2)//6 for l in lsets if l<=p)
                     for p in psets)
    assert independent_triples==triple_count
    # Check matroid connectedness using fundamental circuits relative to
    # the simple-root coordinate basis.  Connect coordinates co-occurring
    # with nonzero coefficients in any root.  If graph is connected, the
    # represented matroid cannot be a nontrivial direct sum.
    neighbors={i:set() for i in range(4)}
    for v in vectors:
        support=[i for i,x in enumerate(v) if x]
        for i,j in combinations(support,2):neighbors[i].add(j);neighbors[j].add(i)
    component={0};pending=[0]
    while pending:
        for j in neighbors[pending.pop()]-component:component.add(j);pending.append(j)
    assert len(component)==4
    points_by_m=Counter(map(len,psets));lines_by_m=Counter(map(len,lsets))
    point_lines=Counter()
    line_points=Counter()
    pcube=0;lcube=0; line_details=[]
    for p in psets:
        hist=Counter(len(l) for l in lsets if l<=p)
        point_lines[(len(p),tuple(sorted(hist.items())))]+=1
        pcube+=(3-len(p))**3
    for l in lsets:
        hist=Counter(len(p) for p in psets if l<=p)
        line_points[(len(l),tuple(sorted(hist.items())))]+=1
        pcount=sum(hist.values());d=n-4+sum(c*(3-m) for m,c in hist.items())
        a=2-len(l); normal=2-2*pcount
        change=-3*a*a*d-a*a*a*normal
        lcube+=change
        line_details.append((len(l),d,normal,change))
    cube=(n-4)**3+pcube+lcube
    # Independent regrouping formula obtained by expanding over point-line
    # flags, without constructing transformed normal bundle degrees.
    independent_cube=(n-4)**3+sum((3-len(p))**3 for p in psets)
    independent_cube-=3*(n-4)*sum((2-len(l))**2 for l in lsets)
    independent_cube-=2*sum((2-len(l))**3 for l in lsets)
    independent_cube+=sum((2-len(l))**2*(2*(2-len(l))-3*(3-len(p)))
                          for p in psets for l in lsets if l<=p)
    assert cube==independent_cube
    line_mu=sum(len(l)-1 for l in lsets)
    point_mu=sum(-1+len(p)-sum(len(l)-1 for l in lsets if l<=p) for p in psets)
    chi=4-3*n+2*line_mu+point_mu
    bottom_mu=-(1-n+line_mu+point_mu)
    characteristic=[1,-n,line_mu,point_mu,bottom_mu]
    # The characteristic polynomial obtained without assuming exponents
    # agrees with a direct elementary product of the expected linear terms.
    exponents={'F4':[1,5,7,11],'H4':[1,11,19,29],
               'A4':[1,2,3,4],'B4':[1,3,5,7]}[kind]
    polynomial=[1]
    for e in exponents:
        new=[0]*(len(polynomial)+1)
        for i,c in enumerate(polynomial):new[i]+=c;new[i+1]-=e*c
        polynomial=new
    assert characteristic==polynomial
    coxeter_euler={'F4':-(5-1)*(7-1)*(11-1),'H4':-(11-1)*(19-1)*(29-1),'A4':-(2-1)*(3-1)*(4-1),'B4':-(3-1)*(5-1)*(7-1)}[kind]
    assert chi==coxeter_euler
    return {'type':kind,'root_count':nroot,'root_line_count':n,
            'cartan':[[v.raw() for v in row] for row in cartan],
            'root_lines':[ [v.raw() for v in row] for row in vectors],
            'rank2_count':len(lsets),'rank3_count':len(psets),
            'rank2_flats':sorted(map(sorted,lsets)),
            'rank3_flats':sorted(map(sorted,psets)),
            'matroid_connected':True,
            'line_histogram':dict(sorted(lines_by_m.items())),
            'point_histogram':dict(sorted(points_by_m.items())),
            'line_point_profiles':[{'multiplicity':m,'point_multiplicities':dict(h),'count':c} for (m,h),c in sorted(line_points.items())],
            'point_line_profiles':[{'multiplicity':m,'line_multiplicities':dict(h),'count':c} for (m,h),c in sorted(point_lines.items())],
            'line_cube_term_profiles':[{'m':m,'d':d,'normal':nu,'term':t,'count':c} for (m,d,nu,t),c in sorted(Counter(line_details).items())],
            'initial_cube':(n-4)**3,'point_correction':pcube,
            'line_correction':lcube,'log_volume':cube,
            'euler_characteristic':chi,'ratio':str(Fraction(cube,abs(chi))),
            'characteristic_polynomial_coefficients':characteristic,
            'independent_triples':independent_triples,'elapsed_seconds':time.time()-started}

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--output',required=True);ap.add_argument('--types',default='F4,H4');a=ap.parse_args()
    out={kind:compute(kind) for kind in a.types.split(',')}
    Path(a.output).write_text(json.dumps(out,indent=2)+'\n')
    print(json.dumps({k:{x:y for x,y in v.items() if x not in {'root_lines','cartan','rank2_flats','rank3_flats'}} for k,v in out.items()},indent=2))
