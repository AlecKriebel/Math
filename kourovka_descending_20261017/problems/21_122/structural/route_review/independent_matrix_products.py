#!/usr/bin/env python3
"""Separate finite controls using affine S3 and planar D8 matrices.

No author code is imported. Infinite-product topology and quantifiers are
proved in REVIEW.md; no finite computation substitutes for those arguments.
"""
from collections import deque
from datetime import datetime, timezone
from hashlib import sha256
from itertools import product
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent
AUTHOR = ROOT.parent
UNIT = (1, 0, 0, 1)


def multiply(a, b, modulus=None):
    c = (a[0]*b[0]+a[1]*b[2], a[0]*b[1]+a[1]*b[3],
         a[2]*b[0]+a[3]*b[2], a[2]*b[1]+a[3]*b[3])
    return tuple(x % modulus for x in c) if modulus else c


def generate(generators, modulus=None):
    known = {UNIT}
    queue = deque([UNIT])
    while queue:
        g = queue.popleft()
        for h in generators:
            gh = multiply(g, h, modulus)
            if gh not in known:
                known.add(gh)
                queue.append(gh)
    return sorted(known)


def tables(group, modulus=None):
    positions = {g: i for i, g in enumerate(group)}
    unit = positions[UNIT]
    mul = [[positions[multiply(g, h, modulus)] for h in group] for g in group]
    inv = [next(j for j in range(len(group))
                if mul[i][j] == unit and mul[j][i] == unit)
           for i in range(len(group))]
    comm = [[mul[mul[mul[inv[i]][inv[j]]][i]][j]
             for j in range(len(group))] for i in range(len(group))]
    return unit, mul, inv, comm


def conjugates(x, mul, inv):
    return {mul[mul[inv[g]][x]][g] for g in range(len(mul))}


def finite_x0_width(factors, unit, mul, involutions):
    identity = (unit,) * factors
    generators = []
    for coordinate in range(factors):
        for transposition in involutions:
            entry = list(identity)
            entry[coordinate] = transposition
            generators.append(tuple(entry))
    distance = {identity: 0}
    queue = deque([identity])
    while queue:
        x = queue.popleft()
        for y in generators:
            xy = tuple(mul[a][b] for a, b in zip(x, y))
            if xy not in distance:
                distance[xy] = distance[x] + 1
                queue.append(xy)
    assert len(distance) == len(mul) ** factors
    assert max(distance.values()) == 2 * factors
    return {'S3_factors': factors, 'X0_size': len(generators)+1,
            'generated_group_size': len(distance), 'maximum_X0_length': 2*factors}


def run():
    # Affine transformations x -> a*x+b on F3 give S3 independently of
    # the author's permutation-list realization.
    s3 = generate([(1, 1, 0, 1), (2, 0, 0, 1)], 3)
    assert len(s3) == 6
    su, sm, si, sc = tables(s3, 3)
    transpositions = [x for x in range(6) if x != su and sm[x][x] == su]
    assert len(transpositions) == 3
    s3_commutators = {x for row in sc for x in row}
    assert len(s3_commutators) == 3
    assert all(sm[sm[x][x]][x] == su for x in s3_commutators)
    conjugacy_sizes = sorted(len(conjugates(x, sm, si)) for x in range(6))
    assert conjugacy_sizes == [1, 2, 2, 3, 3, 3]
    for x in transpositions:
        orbit = conjugates(x, sm, si)
        assert orbit == set(transpositions)
        assert len(generate([s3[t] for t in orbit], 3)) == 6
    product_widths = [finite_x0_width(n, su, sm, transpositions)
                      for n in range(1, 5)]

    # Orthogonal integer matrices generated by quarter-turn and reflection
    # give D8 without the author's (rotation,reflection) multiplication law.
    d8 = generate([(0, -1, 1, 0), (1, 0, 0, -1)])
    assert len(d8) == 8
    du, dm, di, dc = tables(d8)
    minus_unit = d8.index((-1, 0, 0, -1))
    squares = {dm[x][x] for x in range(8)}
    commutators = {x for row in dc for x in row}
    assert squares == commutators == {du, minus_unit}
    assert all(dm[z][x] == dm[x][z] for z in squares for x in range(8))
    assert {dm[z][z] for z in squares} == {du}
    assert {dc[x][y] for x in squares for y in squares} == {du}

    # Directly evaluate word inputs in small finite products, rather than
    # merely forming products of the already computed single-factor images.
    direct_products = []
    for n in range(1, 4):
        elements = list(product(range(8), repeat=n))
        square_values = {tuple(dm[x][x] for x in g) for g in elements}
        commutator_values = {tuple(dc[x][y] for x, y in zip(g, h))
                             for g in elements for h in elements}
        assert square_values == commutator_values
        assert len(square_values) == 2 ** n
        second_squares = {tuple(dm[x][x] for x in z) for z in square_values}
        second_commutators = {tuple(dc[x][y] for x, y in zip(z, t))
                              for z in square_values for t in square_values}
        assert second_squares == second_commutators == {(du,)*n}
        direct_products.append({'D8_factors': n,
                                'full_group_inputs': len(elements),
                                'word_values': len(square_values),
                                'iterated_word_values': 1})

    return {
        'utc': datetime.now(timezone.utc).isoformat(),
        'result': 'PASS_INDEPENDENT_MATRIX_PRODUCT_CONTROLS',
        'method': 'S3 as affine 2x2 matrices over F3; D8 as planar integer matrices; no author imports',
        'S3_order': len(s3), 'S3_nonidentity_involutions': len(transpositions),
        'S3_conjugacy_class_sizes': conjugacy_sizes,
        'S3_commutator_values': len(s3_commutators),
        'S3_product_X0_widths': product_widths,
        'D8_order': len(d8), 'D8_square_and_commutator_values': 2,
        'D8_full_input_product_evaluations': direct_products,
        'author_hashes_at_check': {name: sha256((AUTHOR/name).read_bytes()).hexdigest()
                                   for name in ['FC_WIDTH_AND_MARGINAL_ROUTES.md',
                                                'check_structural_examples.py',
                                                'structural_example_results.json']},
        'scope': 'Finite controls only. S3 generator set X0 is not a word-value set; D8 word-value sets have continuum size in the infinite product. No resolution of Kourovka21.122.'}


if __name__ == '__main__':
    out = run()
    (ROOT/'independent_matrix_results.json').write_text(json.dumps(out, indent=2)+'\n')
    print(json.dumps(out, indent=2))
