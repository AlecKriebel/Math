#!/usr/bin/env python3
"""Independent forward-generation check of the structural sufficient graph grammar.
Seeds use cycle detection and nonedge equivalence. Closure is generated by explicit
labelled disjoint unions and adding one universal vertex. Isomorphism classes use
orbits under adjacent transpositions, rather than permutation canonicalization.
"""
from itertools import combinations
from pathlib import Path
import json


def pairs(n):
    return list(combinations(range(n), 2))


def edge_set(n, mask):
    return {e for k, e in enumerate(pairs(n)) if mask & (1 << k)}


def encode(n, edges):
    return sum(1 << k for k,e in enumerate(pairs(n)) if e in edges)


def forest(n, edges):
    parent = list(range(n))
    def find(x):
        while parent[x] != x:
            x = parent[x]
        return x
    for a,b in sorted(edges):
        a,b = find(a),find(b)
        if a == b:
            return False
        parent[a] = b
    return True


def multipartite3(n, edges):
    # Nonadjacency, including equality, must be an equivalence relation.
    related = lambda a,b: a == b or tuple(sorted((a,b))) not in edges
    for a in range(n):
        for b in range(n):
            for c in range(n):
                if related(a,b) and related(b,c) and not related(a,c):
                    return False
    classes = []
    for a in range(n):
        if not any(related(a,b) for b in classes):
            classes.append(a)
    return len(classes) <= 3


def relabel(n, mask, labels):
    return {tuple(sorted((labels[a],labels[b]))) for a,b in edge_set(n,mask)}


def generate(max_n):
    accepted = []
    for n in range(max_n+1):
        seeds = {mask for mask in range(1 << (n*(n-1)//2))
                 if forest(n, edge_set(n,mask)) or multipartite3(n,edge_set(n,mask))}
        # All finite disjoint unions are obtainable by binary disjoint unions.
        for k in range(1,n):
            for left in combinations(range(n),k):
                right = tuple(v for v in range(n) if v not in left)
                for a in accepted[k]:
                    ea = relabel(k,a,left)
                    for b in accepted[n-k]:
                        seeds.add(encode(n,ea | relabel(n-k,b,right)))
        if n:
            for universal in range(n):
                other = tuple(v for v in range(n) if v != universal)
                star = {tuple(sorted((universal,v))) for v in other}
                for mask in accepted[n-1]:
                    seeds.add(encode(n,star | relabel(n-1,mask,other)))
        accepted.append(seeds)
    return accepted


def orbit(n, mask):
    done = {mask}
    todo = [mask]
    while todo:
        current = todo.pop()
        for a in range(n-1):
            labels = list(range(n))
            labels[a],labels[a+1] = labels[a+1],labels[a]
            new = encode(n,relabel(n,current,labels))
            if new not in done:
                done.add(new)
                todo.append(new)
    return done


def orbit_summary(n, inside):
    remaining = set(range(1 << (n*(n-1)//2)))
    yes,no = 0,[]
    while remaining:
        base = min(remaining)
        current = orbit(n,base)
        assert current <= remaining
        assert current <= inside or not current & inside
        remaining -= current
        if base in inside:
            yes += 1
        else:
            no.append(base)
    return {'vertices': n,'inside': yes,'outside': len(no),
            'outside_canonical_masks': no}


def main():
    accepted = generate(6)
    result = {'method':'forward labelled grammar generation; adjacent-transposition orbits',
              'labelled_counts':[], 'isomorphism_counts':[]}
    for n,current in enumerate(accepted):
        result['labelled_counts'].append({'vertices':n,'inside':len(current),
                                         'outside':(1 << (n*(n-1)//2))-len(current)})
        if n <= 5:
            result['isomorphism_counts'].append(orbit_summary(n,current))
    author=json.loads(Path(__file__).parents[1].joinpath('graph_census.json').read_text())
    assert result['labelled_counts']==author['labelled_counts']
    assert result['isomorphism_counts']==author['isomorphism_counts']
    assert all(len(accepted[n])==(1 << (n*(n-1)//2)) for n in range(5))
    # K_(2,2,2,2) is connected, has no universal vertices, is not a forest,
    # and its four nonadjacency classes disqualify it as a seed.
    fourpart={ (a,b) for a,b in pairs(8) if a//2 != b//2 }
    assert not forest(8,fourpart) and not multipartite3(8,fourpart)
    assert all(any(tuple(sorted((a,b))) not in fourpart for b in range(8) if b!=a)
               for a in range(8))
    # Explicit connectivity witness: each vertex reaches every vertex in at most2 steps.
    assert all(a==b or tuple(sorted((a,b))) in fourpart or
               any(tuple(sorted((a,c))) in fourpart and tuple(sorted((b,c))) in fourpart
                   for c in range(8) if c not in (a,b))
               for a in range(8) for b in range(8))
    result['boundary_checks']={'all_graphs_at_most4_inside':True,'F2_power4_outside':True}
    result['comparison']='PASS: all author JSON counts and canonical outside masks reproduced'
    Path(__file__).with_name('independent_graph_census.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps(result,indent=2))


if __name__=='__main__':
    main()
