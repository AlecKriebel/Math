#!/usr/bin/env python3
"""Exact small controls for envelopes and noncentral torus-by-finite shape."""
from itertools import product
import sympy as s
import json
checks=0

def ck(t):
 global checks
 assert t
 checks+=1
# Non-toral C2 x C2 in PGL2, checked with projective matrices.
projective_cases=0
for p in (3,5,7,11):
 def norm(M):
  M=tuple(v%p for v in M)
  c=next(v for v in M if v)
  return tuple(v*pow(c,-1,p)%p for v in M)
 def mul(A,B):
  a,b,c,d=A;e,f,g,h=B
  return norm((a*e+b*g,a*f+b*h,c*e+d*g,c*f+d*h))
 I=norm((1,0,0,1));A=norm((-1,0,0,1));B=norm((0,1,1,0));AB=mul(A,B)
 H={I,A,B,AB}
 ck(len(H)==4);ck(mul(A,B)==mul(B,A))
 for a,b in product(H,repeat=2):ck(mul(a,b) in H)
 for a in H:ck(mul(a,a)==I)
 # Direct rational-point centralizer of this example is exactly H.
 C=set()
 for a,b,c,d in product(range(p),repeat=4):
  if (a*d-b*c)%p==0:continue
  M=norm((a,b,c,d))
  if all(mul(M,h)==mul(h,M) for h in H):C.add(M)
 ck(C==H);projective_cases+=1
projective_checks=checks
# mu_p in GL2: off-diagonal commutator coefficients force them to vanish,
# even though z^p-1=(z-1)^p is not reduced.
z,b,c=s.symbols('z b c')
for p in (2,3,5,7,11):
 for entry in (b,c):
  rem=s.rem(s.Poly((z-1)*entry,z),s.Poly(z**p-1,z))
  ck(rem.degree()==1);ck(rem.nth(1)==entry and rem.nth(0)==-entry)
 # Quotient diagonal torus character lattice generated by (p,0),(0,1).
 A=s.diag(p,1);ck(A.det()==p);ck(A.rank()==2)
infinitesimal_checks=checks-projective_checks
# Finite analogues of a normal, noncentral identity-torus factor:
# C_m semidirect C2 by inversion. This distinguishes normal rigidification
# from the insufficient central-only version.
semidirect_cases=0
for m in range(3,18):
 def mul(x,y):return ((x[0]+(-1)**x[1]*y[0])%m,(x[1]+y[1])%2)
 def inv(x):return ((-(-1)**x[1]*x[0])%m,x[1])
 T=[(i,0) for i in range(m)];G=list(product(range(m),range(2)))
 for g in G:
  for x in T:ck(mul(mul(g,x),inv(g))[1]==0)
 ck(mul((0,1),(1,0))!=mul((1,0),(0,1)))
 for x,y in product(G,repeat=2):ck(mul(x,y)[1]==(x[1]+y[1])%2)
 semidirect_cases+=1
print(json.dumps({'status':'PASS','exact_assertions':checks,'projective_example_fields':projective_cases,'projective_assertions':projective_checks,'infinitesimal_assertions':infinitesimal_checks,'semidirect_examples':semidirect_cases,'scope':'Finite examples and character/commutator identities only. General centralizer, envelope, rigidification and descent claims rest on the written proof and cited structural theorems.'},indent=2,sort_keys=True))
