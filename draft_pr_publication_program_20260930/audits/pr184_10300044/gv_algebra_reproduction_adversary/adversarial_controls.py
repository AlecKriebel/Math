#!/usr/bin/env python3
"""Own isolated negative controls; never changes original submission files."""
from pathlib import Path
import sys, json, hashlib, datetime, ast, types, dis
from fractions import Fraction
from run_controls import run
OWN=Path(__file__).resolve().parent
PYTHON=OWN/'private/control_env/bin/python'
author=(OWN/'private/author_initial/verify.py').read_text()
reviewer=(OWN/'private/reviewer_copy/independent_checks.py').read_text()
candidate=(OWN/'private/author_initial/CANDIDATE.md').read_text()
manifest=[]
def case(name,kind,source,proof,change,modes=(False,True)):
 d=OWN/'private/mutants'/name;d.mkdir(parents=True,exist_ok=True)
 script=d/('verify.py' if kind=='author' else 'independent_checks.py');script.write_text(source)
 c=d/('CANDIDATE.md' if kind=='author' else 'author_replay/CANDIDATE.md');c.parent.mkdir(parents=True,exist_ok=True);c.write_text(proof)
 row={'name':name,'kind':kind,'change':change,'script_sha256':hashlib.sha256(script.read_bytes()).hexdigest(),'candidate_sha256':hashlib.sha256(c.read_bytes()).hexdigest(),'runs':[]}
 for optimized in modes:
  label=name+('_optimized' if optimized else '_normal')
  argv=[str(PYTHON)]+(['-O'] if optimized else [])+[str(script)]
  status=run(label,argv,[script,c]);row['runs'].append({'label':label,'optimized':optimized,'exit_code':status})
 manifest.append(row)
case('author_baseline','author',author,candidate,'No mutation',modes=(True,))
case('author_false_guard','author',author.replace('root=Path(__file__).resolve().parent','check(False)\nroot=Path(__file__).resolve().parent'),candidate,'Inject an intentionally false scientific guard')
old='density=add(mul(qz,der(pz,2)),scale(mul(pz,der(qz,2)),-1))'
if old not in author:raise RuntimeError('source pattern changed')
case('author_wrong_density','author',author.replace(old,old.replace(',-1)',',1)')),candidate,'Reverse the second GV-density term sign')
if '=Na.' not in candidate:raise RuntimeError('candidate pattern changed')
badproof=candidate.replace('=Na.','=0.',1)
case('author_corrupt_candidate','author',author,badproof,'Change the claimed theorem value from Na to 0',modes=(False,))
case('author_source_comment','author',author+'\n# Deliberate source digest mismatch.\n',candidate,'Alter source bytes without changing arithmetic',modes=(False,))
case('reviewer_baseline','reviewer',reviewer,candidate,'No mutation',modes=(True,))
old='G=s.diff(q,z)*s.diff(p,z,2)-s.diff(p,z)*s.diff(q,z,2)'
if old not in reviewer:raise RuntimeError('reviewer pattern changed')
case('reviewer_wrong_GV_sign','reviewer',reviewer.replace(old,old.replace(')-s.diff',')+s.diff')),candidate,'Reverse the symbolic GV-density sign')
case('reviewer_corrupt_candidate','reviewer',reviewer,badproof,'Change theorem Na to 0 while retaining expected frozen digest')
old='28d66c68f4497b1b2a3476d3f858902e8def73e65357320a743da43cb0564c6f'
case('reviewer_corrupt_expected_digest','reviewer',reviewer.replace(old,'0'*64),candidate,'Replace expected frozen candidate digest with zeros')
(OWN/'receipts/mutation_manifest.json').write_text(json.dumps({'utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'cases':manifest},indent=2,sort_keys=True))
# Actual generator function is isolated from the copied source AST, not assumed from receipts.
tree=ast.parse(author);make=next(n for n in tree.body if isinstance(n,ast.FunctionDef) and n.name=='make')
ns={'F':Fraction,'clean':lambda p:{m:Fraction(c) for m,c in p.items() if c}}
exec(compile(ast.Module(body=[make],type_ignores=[]),'<isolated actual author make>','exec'),ns)
def canonical(p):return tuple(sorted((m,str(c)) for m,c in p.items()))
pairs=[(canonical(ns['make'](2*k)),canonical(ns['make'](2*k+1))) for k in range(120)]
potentials=[canonical(ns['make'](k)) for k in range(50)]
def check_code(src,opt):
 c=compile(src,'<copied verifier>', 'exec',optimize=opt)
 f=next(k for k in c.co_consts if isinstance(k,types.CodeType) and k.co_name=='check')
 return [i.opname for i in dis.get_instructions(f)]
coverage={'actual_author_pair_iterations':len(pairs),'actual_distinct_author_pairs':len(set(pairs)),'actual_author_potential_iterations':len(potentials),'actual_distinct_author_potentials':len(set(potentials)),'actual_distinct_pair_compression_cases':len(set(pairs))*3,'guards':{kind:{'assert_nodes':sum(isinstance(n,ast.Assert) for n in ast.walk(ast.parse(src))),'check_normal_bytecode':check_code(src,0),'check_optimized_bytecode':check_code(src,1)} for kind,src in [('author',author),('reviewer',reviewer)]},'scope':'No global smooth diffeomorphisms, holonomy representation, hyperbolic metric or tautness instance is generated by either original verifier.'}
(OWN/'receipts/coverage_and_guard_inventory.json').write_text(json.dumps(coverage,indent=2,sort_keys=True))
print(json.dumps(coverage,indent=2,sort_keys=True))
