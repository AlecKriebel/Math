 expected['publication/PACKAGE_INPUT_PINS.json']=(PUB/'PACKAGE_INPUT_PINS.json').read_bytes()
 forbidden={'raw','rawprivate','private','cache','caches','__pycache__','tmp','duplicateinputarchives','extracted','reconstruction','render','renders','original_bytes'}
 forbidden_suffixes={'.txt','.pdf','.ps','.eps','.html','.png','.jpg','.jpeg','.gif','.webp','.zip','.pyc','.pyo','.stdout','.stderr'}
 inspected=[]
 with zipfile.ZipFile(PUB/'source_audit_kit.zip') as z:
  require(z.testzip() is None,'CRC failure');require(z.namelist()==sorted(expected),'ZIP inventory mismatch')
  for info in z.infolist():
   n=info.filename; pp=PurePosixPath(n);data=z.read(n)
   require(str(pp)==n and not pp.is_absolute() and '..' not in pp.parts and n.isascii(),'unsafe path')
