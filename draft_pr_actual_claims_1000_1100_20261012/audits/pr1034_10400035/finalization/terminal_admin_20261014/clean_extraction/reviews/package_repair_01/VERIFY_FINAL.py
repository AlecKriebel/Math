import sys
sys.dont_write_bytecode=True
from pathlib import Path, PurePosixPath
import json, hashlib, zipfile, io, re, subprocess, datetime, os, shutil
ROOT=Path(__file__).resolve().parents[2]
PUB=ROOT/'publication'
OWN=Path(__file__).resolve().parent
ENV=dict(os.environ,PYTHONDONTWRITEBYTECODE='1')
def require(cond,message):
 if not cond:raise RuntimeError(message)
def rec(name,data):return {'path':name,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()}
def diskrec(name):return rec(name,(ROOT/name).read_bytes())
def run(cmd,cwd):
 r=subprocess.run(cmd,cwd=cwd,env=ENV,capture_output=True,text=True)
 require(r.returncode==0,f'{cmd}: {r.stderr}')
 return {'command':cmd,'exit_code':r.returncode,'stdout':r.stdout,'stderr':r.stderr}
def main():
 before={n:(PUB/n).read_bytes() for n in ['source_audit_kit.zip','PACKAGE_MANIFEST.json','CANDIDATE_INTEGRITY.json']}
 first=run([sys.executable,'-B','build_package.py'],PUB)
 require(all((PUB/n).read_bytes()==b for n,b in before.items()),'first rebuild changed generated bytes')
 second=run([sys.executable,'-B','build_package.py'],PUB)
